function [t, y, Fs, N_original] = ...
        leer_csv_rigol_terreno(nombre_archivo, Fs_default)

    M = readmatrix(nombre_archivo);

    if size(M, 2) < 2
        error( ...
            'El archivo no tiene al menos dos columnas numericas:\n%s', ...
            nombre_archivo);
    end

    t = M(:, 1);
    y = M(:, 2);

    idx = isfinite(t) & isfinite(y);

    t = t(idx);
    y = y(idx);

    N_original = numel(y);

    if N_original < 10
        error( ...
            'El archivo tiene muy pocas muestras validas:\n%s', ...
            nombre_archivo);
    end

    dt = diff(t);
    dt = dt(isfinite(dt) & dt > 0);

    if isempty(dt)
        Fs = Fs_default;
    else
        Fs = 1 / median(dt, 'omitnan');
    end

    if ~isfinite(Fs) || Fs <= 0
        Fs = Fs_default;
    end
end

function [idx_sel, f_sel_kHz, score_sel_dB] = ...
        seleccionar_candidatos_globales( ...
        f_kHz, ...
        score_dB, ...
        num_candidatos, ...
        dist_min_kHz)

    f_kHz = f_kHz(:);
    score_dB = score_dB(:);

    idx_validos = find( ...
        isfinite(f_kHz) & ...
        isfinite(score_dB));

    if isempty(idx_validos)

        idx_sel = [];
        f_sel_kHz = [];
        score_sel_dB = [];

        return;
    end

    [~, orden_local] = sort( ...
        score_dB(idx_validos), ...
        'descend');

    idx_ordenados = idx_validos(orden_local);

    idx_sel = [];

    for i = 1:numel(idx_ordenados)

        idx_actual = idx_ordenados(i);
        f_actual = f_kHz(idx_actual);

        if isempty(idx_sel)

            idx_sel = idx_actual;
        else

            f_previas = f_kHz(idx_sel);

            if all(abs(f_actual - f_previas) >= dist_min_kHz)
                idx_sel = [idx_sel; idx_actual];
            end
        end

        if numel(idx_sel) >= num_candidatos
            break;
        end
    end

    f_sel_kHz = f_kHz(idx_sel);
    score_sel_dB = score_dB(idx_sel);
end

