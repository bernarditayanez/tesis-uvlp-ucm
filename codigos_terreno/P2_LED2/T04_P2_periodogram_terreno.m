function data_cell = formatear_tabla_para_figura(tabla)

    nfilas = height(tabla);
    ncols = width(tabla);

    data_cell = cell(nfilas, ncols);

    nombres = tabla.Properties.VariableNames;

    for c = 1:ncols

        nombre = nombres{c};
        col = tabla.(nombre);

        for i = 1:nfilas

            if iscell(col)
                valor = col{i};
            else
                valor = col(i);
            end

            if isnumeric(valor)

                if isnan(valor)

                    texto = '';

                elseif contains( ...
                        nombre, ...
                        'kHz', ...
                        'IgnoreCase', ...
                        true)

                    texto = sprintf('%.4f', valor);

                elseif contains( ...
                        nombre, ...
                        'Hz', ...
                        'IgnoreCase', ...
                        true)

                    texto = sprintf('%.0f', valor);

                elseif contains( ...
                        nombre, ...
                        'dB', ...
                        'IgnoreCase', ...
                        true)

                    texto = sprintf('%.4f', valor);

                elseif contains( ...
                        nombre, ...
                        'rep', ...
                        'IgnoreCase', ...
                        true)

                    texto = sprintf('%.0f', valor);

                else
                    texto = sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor
                    texto = 'Si';
                else
                    texto = 'No';
                end

            elseif isstring(valor)

                if strlength(valor) == 0
                    texto = '';
                else
                    texto = char(valor);
                end

            elseif ischar(valor)

                texto = valor;

            else
                texto = char(string(valor));
            end

            data_cell{i, c} = texto;
        end
    end
end

function [x_out, y1_out, y2_out] = ...
        reducir_puntos_grafico(x, y1, y2, nmax)

    x = x(:);
    y1 = y1(:);
    y2 = y2(:);

    n = numel(x);

    if n > nmax
        idx = round(linspace(1, n, nmax));
    else
        idx = 1:n;
    end

    x_out = x(idx);
    y1_out = y1(idx);
    y2_out = y2(idx);
end