%% T03_P1_multitaper_terreno.m
% Analisis Multitaper - P1 / LED terreno 1
%
% Antes de ejecutar este script, modificar las variables carpeta_ON
% y carpeta_OFF con las rutas locales donde se encuentran los archivos .csv
% de la medicion correspondiente.
%
% La carpeta_ON debe contener los archivos ON_P1_REP*.csv indicados
% en la lista archivos_ON.
% La carpeta_OFF debe contener los archivos OFF comunes indicados
% en la lista archivos_OFF.
%
% Ejemplo:
% carpeta_ON  = 'C:\Users\NombreUsuario\Desktop\Terreno_ON_M1';
% carpeta_OFF = 'C:\Users\NombreUsuario\Desktop\Terreno_OFF';

clear;
clc;
close all;

%% 1. Configuracion

carpeta_base = 'C:\Users\mudrood\Desktop\Modulo Prof\Archivos Tesis\Toma de Datos\Pruebas en terreno';

carpeta_ON = fullfile(carpeta_base, 'Terreno_ON_M1');
carpeta_OFF = fullfile(carpeta_base, 'Terreno_OFF');

carpeta_salida = fullfile( ...
    carpeta_base, ...
    'Resultados_Terreno', ...
    'P1_LED1', ...
    '03_Multitaper');

if ~exist(carpeta_salida, 'dir')
    mkdir(carpeta_salida);
end

% Eliminar archivos FIG heredados de versiones anteriores.
archivos_fig_anteriores = dir( ...
    fullfile(carpeta_salida, '*P1_multitaper*.fig'));

for k = 1:numel(archivos_fig_anteriores)

    delete(fullfile( ...
        archivos_fig_anteriores(k).folder, ...
        archivos_fig_anteriores(k).name));
end

nombre_punto = "P1";
nombre_led = "LED terreno 1";
nombre_metodo = "Multitaper";

nRep = 3;

archivos_ON = cell(nRep, 1);
archivos_OFF = cell(nRep, 1);

for r = 1:nRep

    archivos_ON{r} = fullfile( ...
        carpeta_ON, ...
        sprintf('ON_P1_REP%d.csv', r));

    archivos_OFF{r} = fullfile( ...
        carpeta_OFF, ...
        sprintf('OFF_REP%d.csv', r));
end

% Banda completa calculada y mostrada
fmin_Hz = 30e3;
fmax_Hz = 90e3;

% Referencia obtenida mediante Periodograma
f_ref_periodograma_Hz = 45.642e3;

% Ventana local usada para confirmar la frecuencia
semiancho_busqueda_local_Hz = 1e3;

% Criterio operativo
criterio_dB = 3;

% Candidatos locales
num_candidatos = 7;
distancia_minima_Hz = 150;
ventana_refinamiento_Hz = 100;
ventana_repetibilidad_Hz = 200;

% Adquisicion
Fs_configurada_Hz = 50e6;

% Multitaper
NW = 2.5;
NFFT = 2^20;

% Figura de rango amplio
fmax_amplio_Hz = 5e6;

limite_local_inferior_Hz = max( ...
    fmin_Hz, ...
    f_ref_periodograma_Hz - semiancho_busqueda_local_Hz);

limite_local_superior_Hz = min( ...
    fmax_Hz, ...
    f_ref_periodograma_Hz + semiancho_busqueda_local_Hz);

fprintf('\n============================================================\n');
fprintf('PUNTO 1 / LED TERRENO 1 - MULTITAPER\n');
fprintf('============================================================\n');
fprintf('Carpeta base:\n%s\n\n', carpeta_base);
fprintf('Carpeta salida:\n%s\n\n', carpeta_salida);
fprintf('Fs configurada: %.6f MSa/s\n', Fs_configurada_Hz/1e6);
fprintf('Banda completa: %.1f a %.1f kHz\n', ...
    fmin_Hz/1e3, fmax_Hz/1e3);
fprintf('Referencia Periodograma: %.4f kHz\n', ...
    f_ref_periodograma_Hz/1e3);
fprintf('Ventana local: %.4f a %.4f kHz\n', ...
    limite_local_inferior_Hz/1e3, ...
    limite_local_superior_Hz/1e3);
fprintf('NW: %.2f\n', NW);
fprintf('NFFT: %d\n', NFFT);
fprintf('Resolucion de grilla: %.6f Hz\n', ...
    Fs_configurada_Hz/NFFT);

%% 2. Verificacion de archivos

for r = 1:nRep

    if ~isfile(archivos_ON{r})

        error( ...
            'No existe el archivo ON de la repeticion %d:\n%s', ...
            r, archivos_ON{r});
    end

    if ~isfile(archivos_OFF{r})

        error( ...
            'No existe el archivo OFF de la repeticion %d:\n%s', ...
            r, archivos_OFF{r});
    end
end

fprintf('\nArchivos verificados correctamente.\n');

%% 3. Calculo Multitaper por repeticion

f_ref_Hz = [];
PSD_ON_mat_dB = [];
PSD_OFF_mat_dB = [];
info_repeticiones = table();

for r = 1:nRep

    fprintf('\n------------------------------------------------------------\n');
    fprintf('Repeticion %d/%d\n', r, nRep);
    fprintf('ON : %s\n', archivos_ON{r});
    fprintf('OFF: %s\n', archivos_OFF{r});

    [tON, xON] = leer_csv_rigol_terreno(archivos_ON{r});
    [tOFF, xOFF] = leer_csv_rigol_terreno(archivos_OFF{r});

    N_ON_original = numel(xON);
    N_OFF_original = numel(xOFF);
    N_usado = min(N_ON_original, N_OFF_original);

    if N_usado < 1000

        error( ...
            'La repeticion %d contiene muy pocas muestras validas.', ...
            r);
    end

    tON = tON(1:N_usado);
    xON = xON(1:N_usado);

    tOFF = tOFF(1:N_usado);
    xOFF = xOFF(1:N_usado);

    duracion_ON_s = tON(end) - tON(1);
    duracion_OFF_s = tOFF(end) - tOFF(1);

    if duracion_ON_s <= 0 || duracion_OFF_s <= 0

        error( ...
            'El vector de tiempo no posee una duracion valida.');
    end

    Fs_ON_duracion_Hz = ...
        (N_usado - 1)/duracion_ON_s;

    Fs_OFF_duracion_Hz = ...
        (N_usado - 1)/duracion_OFF_s;

    error_Fs_ON_pct = abs( ...
        Fs_ON_duracion_Hz - Fs_configurada_Hz) / ...
        Fs_configurada_Hz * 100;

    error_Fs_OFF_pct = abs( ...
        Fs_OFF_duracion_Hz - Fs_configurada_Hz) / ...
        Fs_configurada_Hz * 100;

    if error_Fs_ON_pct > 1

        warning( ...
            ['La Fs estimada para ON difiere mas de 1 %% ', ...
             'respecto de 50 MSa/s en la repeticion %d.'], ...
            r);
    end

    if error_Fs_OFF_pct > 1

        warning( ...
            ['La Fs estimada para OFF difiere mas de 1 %% ', ...
             'respecto de 50 MSa/s en la repeticion %d.'], ...
            r);
    end

    xON = xON - mean(xON, 'omitnan');
    xOFF = xOFF - mean(xOFF, 'omitnan');

    xON(~isfinite(xON)) = 0;
    xOFF(~isfinite(xOFF)) = 0;

    [Pxx_ON, fON_Hz] = pmtm( ...
        xON, ...
        NW, ...
        NFFT, ...
        Fs_configurada_Hz);

    [Pxx_OFF, fOFF_Hz] = pmtm( ...
        xOFF, ...
        NW, ...
        NFFT, ...
        Fs_configurada_Hz);

    fON_Hz = fON_Hz(:);
    fOFF_Hz = fOFF_Hz(:);

    PSD_ON_dB = 10*log10(Pxx_ON(:) + eps);
    PSD_OFF_dB = 10*log10(Pxx_OFF(:) + eps);

    if numel(fON_Hz) ~= numel(fOFF_Hz) || ...
            max(abs(fON_Hz - fOFF_Hz)) > 1e-9

        error( ...
            'Las grillas ON y OFF no coinciden en la repeticion %d.', ...
            r);
    end

    if max(fON_Hz) < fmax_Hz

        error( ...
            'La grilla Multitaper no cubre la banda de 30 a 90 kHz.');
    end

    if isempty(f_ref_Hz)

        f_ref_Hz = fON_Hz;

        PSD_ON_mat_dB = ...
            nan(numel(f_ref_Hz), nRep);

        PSD_OFF_mat_dB = ...
            nan(numel(f_ref_Hz), nRep);
    end

    PSD_ON_mat_dB(:, r) = interp1( ...
        fON_Hz, ...
        PSD_ON_dB, ...
        f_ref_Hz, ...
        'linear', ...
        NaN);

    PSD_OFF_mat_dB(:, r) = interp1( ...
        fOFF_Hz, ...
        PSD_OFF_dB, ...
        f_ref_Hz, ...
        'linear', ...
        NaN);

    info_repeticiones = [ ...
        info_repeticiones; ...
        crear_fila_info( ...
        string(archivos_ON{r}), ...
        "ON", ...
        r, ...
        N_ON_original, ...
        N_usado, ...
        duracion_ON_s, ...
        Fs_ON_duracion_Hz, ...
        Fs_configurada_Hz, ...
        error_Fs_ON_pct, ...
        NW, ...
        NFFT, ...
        Fs_configurada_Hz/NFFT)];

    info_repeticiones = [ ...
        info_repeticiones; ...
        crear_fila_info( ...
        string(archivos_OFF{r}), ...
        "OFF", ...
        r, ...
        N_OFF_original, ...
        N_usado, ...
        duracion_OFF_s, ...
        Fs_OFF_duracion_Hz, ...
        Fs_configurada_Hz, ...
        error_Fs_OFF_pct, ...
        NW, ...
        NFFT, ...
        Fs_configurada_Hz/NFFT)];

    fprintf('N usado             = %d muestras\n', N_usado);
    fprintf('Fs ON por duracion  = %.6f MSa/s\n', ...
        Fs_ON_duracion_Hz/1e6);
    fprintf('Fs OFF por duracion = %.6f MSa/s\n', ...
        Fs_OFF_duracion_Hz/1e6);

    clear tON tOFF xON xOFF
    clear Pxx_ON Pxx_OFF PSD_ON_dB PSD_OFF_dB
end

%% 4. Promedios y score ON-OFF

PSD_ON_prom_dB = mean( ...
    PSD_ON_mat_dB, ...
    2, ...
    'omitnan');

PSD_OFF_prom_dB = mean( ...
    PSD_OFF_mat_dB, ...
    2, ...
    'omitnan');

% Cada captura ON se compara con la referencia OFF promedio.
score_rep_dB = ...
    PSD_ON_mat_dB - PSD_OFF_prom_dB;

score_prom_dB = mean( ...
    score_rep_dB, ...
    2, ...
    'omitnan');

f_ref_Hz = f_ref_Hz(:);
PSD_ON_prom_dB = PSD_ON_prom_dB(:);
PSD_OFF_prom_dB = PSD_OFF_prom_dB(:);
score_prom_dB = score_prom_dB(:);

%% 5. Banda completa de analisis

idx_banda = ...
    f_ref_Hz >= fmin_Hz & ...
    f_ref_Hz <= fmax_Hz;

if ~any(idx_banda)

    error( ...
        'No existen puntos dentro de la banda de 30 a 90 kHz.');
end

f_banda_Hz = ...
    f_ref_Hz(idx_banda);

PSD_ON_banda_dB = ...
    PSD_ON_prom_dB(idx_banda);

PSD_OFF_banda_dB = ...
    PSD_OFF_prom_dB(idx_banda);

score_banda_dB = ...
    score_prom_dB(idx_banda);

PSD_ON_banda_reps_dB = ...
    PSD_ON_mat_dB(idx_banda, :);

PSD_OFF_banda_reps_dB = ...
    PSD_OFF_mat_dB(idx_banda, :);

score_banda_reps_dB = ...
    score_rep_dB(idx_banda, :);

idx_validos = ...
    isfinite(f_banda_Hz) & ...
    isfinite(PSD_ON_banda_dB) & ...
    isfinite(PSD_OFF_banda_dB) & ...
    isfinite(score_banda_dB);

f_banda_Hz = ...
    f_banda_Hz(idx_validos);

PSD_ON_banda_dB = ...
    PSD_ON_banda_dB(idx_validos);

PSD_OFF_banda_dB = ...
    PSD_OFF_banda_dB(idx_validos);

score_banda_dB = ...
    score_banda_dB(idx_validos);

PSD_ON_banda_reps_dB = ...
    PSD_ON_banda_reps_dB(idx_validos, :);

PSD_OFF_banda_reps_dB = ...
    PSD_OFF_banda_reps_dB(idx_validos, :);

score_banda_reps_dB = ...
    score_banda_reps_dB(idx_validos, :);

f_banda_kHz = f_banda_Hz/1e3;

%% 6. Maximo global solo como diagnostico

[score_max_global_dB, idx_max_global] = ...
    max(score_banda_dB);

f_max_global_Hz = ...
    f_banda_Hz(idx_max_global);

fprintf('\n============================================================\n');
fprintf('MAXIMO GLOBAL - SOLO DIAGNOSTICO\n');
fprintf('============================================================\n');
fprintf('Frecuencia global = %.4f kHz\n', ...
    f_max_global_Hz/1e3);
fprintf('Score global      = %.4f dB\n', ...
    score_max_global_dB);

%% 7. Ventana local de confirmacion

idx_busqueda_local = ...
    f_banda_Hz >= limite_local_inferior_Hz & ...
    f_banda_Hz <= limite_local_superior_Hz;

if ~any(idx_busqueda_local)

    error( ...
        'No existen puntos dentro de la ventana local Multitaper.');
end

f_busqueda_local_Hz = ...
    f_banda_Hz(idx_busqueda_local);

score_busqueda_local_dB = ...
    score_banda_dB(idx_busqueda_local);

[score_max_local_dB, idx_max_local] = ...
    max(score_busqueda_local_dB);

f_max_local_Hz = ...
    f_busqueda_local_Hz(idx_max_local);

fprintf('\n============================================================\n');
fprintf('MAXIMO LOCAL MULTITAPER\n');
fprintf('============================================================\n');
fprintf('Referencia Periodograma = %.4f kHz\n', ...
    f_ref_periodograma_Hz/1e3);
fprintf('Frecuencia local        = %.4f kHz\n', ...
    f_max_local_Hz/1e3);
fprintf('Score local             = %.4f dB\n', ...
    score_max_local_dB);

%% 8. Candidatos dentro de la ventana local

[picos_dB, frecuencias_picos_Hz] = findpeaks( ...
    score_busqueda_local_dB, ...
    f_busqueda_local_Hz, ...
    'MinPeakDistance', ...
    distancia_minima_Hz);

idx_picos_validos = ...
    isfinite(picos_dB) & ...
    isfinite(frecuencias_picos_Hz) & ...
    picos_dB > 0;

picos_dB = ...
    picos_dB(idx_picos_validos);

frecuencias_picos_Hz = ...
    frecuencias_picos_Hz(idx_picos_validos);

if isempty(picos_dB)

    picos_dB = ...
        score_max_local_dB;

    frecuencias_picos_Hz = ...
        f_max_local_Hz;
end

[picos_dB, idx_orden] = sort( ...
    picos_dB, ...
    'descend');

frecuencias_picos_Hz = ...
    frecuencias_picos_Hz(idx_orden);

num_candidatos_usados = min( ...
    num_candidatos, ...
    numel(picos_dB));

score_peak_dB = ...
    picos_dB(1:num_candidatos_usados);

fc_candidatas_Hz = ...
    frecuencias_picos_Hz(1:num_candidatos_usados);

nCandidatos = ...
    numel(fc_candidatas_Hz);

score_local_dB = ...
    nan(nCandidatos, 1);

f_local_Hz = ...
    nan(nCandidatos, 1);

ON_dB = ...
    nan(nCandidatos, 1);

OFF_dB = ...
    nan(nCandidatos, 1);

rep_positivas = ...
    zeros(nCandidatos, 1);

rep_3dB = ...
    zeros(nCandidatos, 1);

for i = 1:nCandidatos

    fc_Hz = ...
        fc_candidatas_Hz(i);

    idx_local = ...
        f_ref_Hz >= fc_Hz - ventana_refinamiento_Hz & ...
        f_ref_Hz <= fc_Hz + ventana_refinamiento_Hz & ...
        f_ref_Hz >= limite_local_inferior_Hz & ...
        f_ref_Hz <= limite_local_superior_Hz;

    f_local_temp_Hz = ...
        f_ref_Hz(idx_local);

    score_local_temp_dB = ...
        score_prom_dB(idx_local);

    if isempty(score_local_temp_dB)
        continue;
    end

    [score_local_dB(i), idx_max] = ...
        max(score_local_temp_dB);

    f_local_Hz(i) = ...
        f_local_temp_Hz(idx_max);

    ON_dB(i) = interp1( ...
        f_ref_Hz, ...
        PSD_ON_prom_dB, ...
        f_local_Hz(i), ...
        'linear', ...
        NaN);

    OFF_dB(i) = interp1( ...
        f_ref_Hz, ...
        PSD_OFF_prom_dB, ...
        f_local_Hz(i), ...
        'linear', ...
        NaN);

    idx_rep = ...
        f_ref_Hz >= ...
        f_local_Hz(i) - ventana_repetibilidad_Hz & ...
        f_ref_Hz <= ...
        f_local_Hz(i) + ventana_repetibilidad_Hz;

    for r = 1:nRep

        score_rep_local = ...
            score_rep_dB(idx_rep, r);

        score_rep_max_dB = ...
            max(score_rep_local, [], 'omitnan');

        if isfinite(score_rep_max_dB)

            rep_positivas(i) = ...
                rep_positivas(i) + ...
                double(score_rep_max_dB > 0);

            rep_3dB(i) = ...
                rep_3dB(i) + ...
                double(score_rep_max_dB >= criterio_dB);
        end
    end
end

idx_finitos = ...
    isfinite(f_local_Hz) & ...
    isfinite(score_local_dB) & ...
    isfinite(ON_dB) & ...
    isfinite(OFF_dB);

fc_candidatas_Hz = ...
    fc_candidatas_Hz(idx_finitos);

score_peak_dB = ...
    score_peak_dB(idx_finitos);

f_local_Hz = ...
    f_local_Hz(idx_finitos);

score_local_dB = ...
    score_local_dB(idx_finitos);

ON_dB = ...
    ON_dB(idx_finitos);

OFF_dB = ...
    OFF_dB(idx_finitos);

rep_positivas = ...
    rep_positivas(idx_finitos);

rep_3dB = ...
    rep_3dB(idx_finitos);

if isempty(f_local_Hz)

    error( ...
        'No fue posible obtener candidatos locales validos.');
end

% Evitar candidatos repetidos despues del refinamiento.
[f_local_unicos_Hz, idx_unicos] = unique( ...
    f_local_Hz, ...
    'stable');

f_local_Hz = ...
    f_local_unicos_Hz;

fc_candidatas_Hz = ...
    fc_candidatas_Hz(idx_unicos);

score_peak_dB = ...
    score_peak_dB(idx_unicos);

score_local_dB = ...
    score_local_dB(idx_unicos);

ON_dB = ...
    ON_dB(idx_unicos);

OFF_dB = ...
    OFF_dB(idx_unicos);

rep_positivas = ...
    rep_positivas(idx_unicos);

rep_3dB = ...
    rep_3dB(idx_unicos);

nCandidatos = ...
    numel(f_local_Hz);

supera_3dB = ...
    score_local_dB >= criterio_dB & ...
    rep_3dB == nRep;

tabla_candidatos = table( ...
    fc_candidatas_Hz, ...
    fc_candidatas_Hz/1e3, ...
    score_peak_dB, ...
    f_local_Hz, ...
    f_local_Hz/1e3, ...
    score_local_dB, ...
    ON_dB, ...
    OFF_dB, ...
    rep_positivas, ...
    rep_3dB, ...
    repmat(nRep, nCandidatos, 1), ...
    supera_3dB, ...
    'VariableNames', { ...
    'fc_Hz', ...
    'fc_kHz', ...
    'score_peak_dB', ...
    'f_local_Hz', ...
    'f_local_kHz', ...
    'score_local_dB', ...
    'ON_dB', ...
    'OFF_dB', ...
    'rep_positivas', ...
    'rep_3dB', ...
    'rep_totales', ...
    'supera_3dB'});

tabla_candidatos = sortrows( ...
    tabla_candidatos, ...
    'score_local_dB', ...
    'descend');

%% 9. Seleccion de frecuencia principal

idx_validos_3dB = ...
    tabla_candidatos.supera_3dB;

if any(idx_validos_3dB)

    tabla_validos = ...
        tabla_candidatos(idx_validos_3dB, :);

    [~, idx_mejor] = ...
        max(tabla_validos.score_local_dB);

    fila_principal = ...
        tabla_validos(idx_mejor, :);

else

    warning( ...
        ['Ningun candidato local supera 3 dB en las tres ', ...
         'repeticiones. Se utilizara el mayor candidato local ', ...
         'como resultado provisional.']);

    fila_principal = ...
        tabla_candidatos(1, :);
end

fc_principal_Hz = ...
    fila_principal.f_local_Hz;

fc_principal_kHz = ...
    fila_principal.f_local_kHz;

score_principal_dB = ...
    fila_principal.score_local_dB;

ON_principal_dB = ...
    fila_principal.ON_dB;

OFF_principal_dB = ...
    fila_principal.OFF_dB;

rep_positivas_principal = ...
    fila_principal.rep_positivas;

rep_3dB_principal = ...
    fila_principal.rep_3dB;

if score_principal_dB >= criterio_dB && ...
        rep_3dB_principal == nRep

    supera_criterio = "Si";

else

    supera_criterio = "No";
end

%% 10. Frecuencia y score por repeticion

idx_rep_principal = ...
    f_ref_Hz >= ...
    fc_principal_Hz - ventana_repetibilidad_Hz & ...
    f_ref_Hz <= ...
    fc_principal_Hz + ventana_repetibilidad_Hz;

f_rep_principal_Hz = ...
    f_ref_Hz(idx_rep_principal);

if isempty(f_rep_principal_Hz)

    error( ...
        'No existen puntos para evaluar la repetibilidad.');
end

fc_por_rep_Hz = ...
    nan(nRep, 1);

score_por_rep_dB = ...
    nan(nRep, 1);

score_positivo_0dB = ...
    false(nRep, 1);

score_positivo_3dB = ...
    false(nRep, 1);

for r = 1:nRep

    score_temp_dB = ...
        score_rep_dB(idx_rep_principal, r);

    [score_por_rep_dB(r), idx_rep_max] = ...
        max(score_temp_dB, [], 'omitnan');

    fc_por_rep_Hz(r) = ...
        f_rep_principal_Hz(idx_rep_max);

    score_positivo_0dB(r) = ...
        score_por_rep_dB(r) > 0;

    score_positivo_3dB(r) = ...
        score_por_rep_dB(r) >= criterio_dB;
end

