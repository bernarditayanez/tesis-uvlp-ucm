function [t, y] = leer_csv_rigol_terreno(nombre_archivo)

    if ~isfile(nombre_archivo)

        error( ...
            'No se encuentra el archivo:\n%s', ...
            nombre_archivo);
    end

    M = readmatrix(nombre_archivo);

    if size(M, 2) < 2

        error( ...
            ['El archivo no contiene al menos dos columnas ', ...
             'numericas:\n%s'], ...
            nombre_archivo);
    end

    columnas_validas = [];

    for c = 1:size(M, 2)

        if sum(isfinite(M(:, c))) > 10

            columnas_validas = [ ...
                columnas_validas, ...
                c]; %#ok<AGROW>
        end
    end

    if numel(columnas_validas) < 2

        error( ...
            ['No se detectaron dos columnas numericas validas ', ...
             'en:\n%s'], ...
            nombre_archivo);
    end

    t = M(:, columnas_validas(1));
    y = M(:, columnas_validas(2));

    idx_validos = ...
        isfinite(t) & ...
        isfinite(y);

    t = t(idx_validos);
    y = y(idx_validos);

    t = t(:);
    y = y(:);

    if numel(y) < 10

        error( ...
            ['El archivo contiene muy pocas muestras validas ', ...
             'en:\n%s'], ...
            nombre_archivo);
    end
end

