    nombre_led, ...
    nombre_metodo, ...
    f_ref_periodograma_Hz/1e3, ...
    semiancho_busqueda_local_Hz/1e3, ...
    fc_principal_kHz, ...
    score_principal_dB, ...
    ON_principal_dB, ...
    OFF_principal_dB, ...
    rep_positivas_principal, ...
    rep_3dB_principal, ...
    nRep, ...
    criterio_dB, ...
    supera_criterio, ...
    NW, ...
    NFFT, ...
    Fs_configurada_Hz/NFFT, ...
    'VariableNames', { ...
    'punto', ...
    'led', ...
    'metodo', ...
    'f_ref_periodograma_kHz', ...
    'semiancho_local_kHz', ...
    'fc_detectada_kHz', ...
    'score_dB', ...
    'ON_prom_dB', ...
    'OFF_prom_dB', ...
    'rep_positivas', ...
    'rep_3dB', ...
    'rep_totales', ...
    'criterio_dB', ...
    'supera_3dB', ...
    'NW', ...
    'NFFT', ...
