function guardar_tabla_png( ...
    tabla, ...
    titulo_tabla, ...
    archivo_png)

    if isempty(tabla)

        warning( ...
            'La tabla esta vacia. No se guardara la figura.');

        return;
    end

    datos = ...
        formatear_tabla_para_figura(tabla);

    nombres = ...
        tabla.Properties.VariableNames;

    nFilas = ...
        height(tabla);

    nColumnas = ...
        width(tabla);

    ancho_columnas = ...
        zeros(1, nColumnas);

    for c = 1:nColumnas

        largo_maximo = ...
            length(nombres{c});

        for i = 1:nFilas

            largo_maximo = max( ...
                largo_maximo, ...
                length(datos{i, c}));
        end

        ancho_columnas(c) = max( ...
            75, ...
            min(155, 8*largo_maximo + 24));
    end

    margen_izquierdo = 30;
    margen_derecho = 30;
    margen_inferior = 25;

    alto_titulo = 55;
    alto_fila = 28;
    alto_encabezado = 30;

    ancho_tabla = ...
        sum(ancho_columnas);

    alto_tabla = ...
        alto_encabezado + nFilas*alto_fila;

    ancho_figura = ...
        margen_izquierdo + ancho_tabla + margen_derecho;

    alto_figura = ...
        margen_inferior + alto_tabla + alto_titulo + 15;

    fig = figure( ...
        'Color', 'w', ...
        'Units', 'pixels', ...
        'Position', [ ...
        100, ...
        100, ...
        ancho_figura, ...
        alto_figura]);

    ax = axes( ...
        'Parent', fig, ...
        'Units', 'pixels', ...
        'Position', [ ...
        0, ...
        0, ...
        ancho_figura, ...
        alto_figura]);

    axis(ax, [0 ancho_figura 0 alto_figura]);
    axis(ax, 'off');
    hold(ax, 'on');

    text( ...
        ax, ...
        ancho_figura/2, ...
        alto_figura - 28, ...
        titulo_tabla, ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontWeight', 'bold', ...
        'FontSize', 15, ...
        'Interpreter', 'none');

    x0 = margen_izquierdo;
    y0 = margen_inferior + alto_tabla;

    color_encabezado = [0.93 0.93 0.93];
    color_fila_1 = [1 1 1];
    color_fila_2 = [0.94 0.94 0.94];
    color_borde = [0.65 0.65 0.65];

    x = x0;

    for c = 1:nColumnas

        rectangle( ...
            ax, ...
            'Position', [ ...
            x, ...
            y0 - alto_encabezado, ...
            ancho_columnas(c), ...
            alto_encabezado], ...
            'FaceColor', color_encabezado, ...
            'EdgeColor', color_borde, ...
            'LineWidth', 0.8);

        text( ...
            ax, ...
            x + ancho_columnas(c)/2, ...
            y0 - alto_encabezado/2, ...
            nombres{c}, ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'FontWeight', 'bold', ...
            'FontSize', 9, ...
            'Interpreter', 'none');

        x = x + ancho_columnas(c);
    end

    for i = 1:nFilas

        y = ...
            y0 - alto_encabezado - i*alto_fila;

        if mod(i, 2) == 0

            color_fila = color_fila_2;

        else

            color_fila = color_fila_1;
        end

        x = x0;

        for c = 1:nColumnas

            rectangle( ...
                ax, ...
                'Position', [ ...
                x, ...
                y, ...
                ancho_columnas(c), ...
                alto_fila], ...
                'FaceColor', color_fila, ...
                'EdgeColor', [0.88 0.88 0.88], ...
                'LineWidth', 0.5);

            text( ...
                ax, ...
                x + ancho_columnas(c)/2, ...
                y + alto_fila/2, ...
                datos{i, c}, ...
                'HorizontalAlignment', 'center', ...
                'VerticalAlignment', 'middle', ...
                'FontSize', 9, ...
                'Interpreter', 'none');

            x = x + ancho_columnas(c);
        end
    end

    drawnow;

    print( ...
        fig, ...
        archivo_png, ...
        '-dpng', ...
        '-r300');
end

function datos = formatear_tabla_para_figura(tabla)

    nFilas = ...
        height(tabla);

    nColumnas = ...
        width(tabla);

    datos = ...
        cell(nFilas, nColumnas);

    nombres = ...
        tabla.Properties.VariableNames;

    for c = 1:nColumnas

        nombre = ...
            nombres{c};

        columna = ...
            tabla.(nombre);

        for i = 1:nFilas

            if iscell(columna)

                valor = ...
                    columna{i};

            else

                valor = ...
                    columna(i);
            end

            if isnumeric(valor)

                if isnan(valor)

                    texto = '';

                elseif contains( ...
                        nombre, ...
                        'kHz', ...
                        'IgnoreCase', true)

                    texto = ...
                        sprintf('%.4f', valor);

                elseif contains( ...
                        nombre, ...
                        'Hz', ...
                        'IgnoreCase', true)

                    texto = ...
                        sprintf('%.4f', valor);

                elseif contains( ...
                        nombre, ...
                        'dB', ...
                        'IgnoreCase', true)

                    texto = ...
                        sprintf('%.4f', valor);

                elseif contains( ...
                        nombre, ...
                        'rep', ...
                        'IgnoreCase', true)

                    texto = ...
                        sprintf('%.0f', valor);

                elseif contains( ...
                        nombre, ...
                        'NW', ...
                        'IgnoreCase', true)

                    texto = ...
                        sprintf('%.2f', valor);

                else

                    texto = ...
                        sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor

                    texto = 'Si';

                else

                    texto = 'No';
                end

            elseif isstring(valor)

                texto = ...
                    char(valor);

            elseif ischar(valor)

                texto = ...
                    valor;

            else

                texto = ...
                    char(string(valor));
            end

            datos{i, c} = ...
                texto;
        end
    end
end

function [x_salida, y1_salida, y2_salida] = ...
    reducir_puntos_grafico( ...
    x, ...
    y1, ...
    y2, ...
    nMaximo)

    x = x(:);
    y1 = y1(:);
    y2 = y2(:);

    nPuntos = ...
        numel(x);

    if nPuntos > nMaximo

        indices = round( ...
            linspace(1, nPuntos, nMaximo));

    else

        indices = ...
            1:nPuntos;
    end

    x_salida = ...
        x(indices);

    y1_salida = ...
        y1(indices);

    y2_salida = ...
        y2(indices);
end