function resultado = calcular_metodo_comparativo( ...
    metodo_actual, ...
    archivos_ON, ...
    archivos_OFF, ...
    parametros)

    nRep = numel(archivos_ON);

    f_ref_Hz = [];
    PSD_ON_mat_dB = [];
    PSD_OFF_mat_dB = [];

    info_repeticiones = table();

    for r = 1:nRep

        fprintf('\n------------------------------------------------------------\n');
        fprintf('Metodo %s - Repeticion %d/%d\n', ...
            metodo_actual.nombre_visible, ...
            r, ...
            nRep);

        fprintf('ON : %s\n', archivos_ON{r});
        fprintf('OFF: %s\n', archivos_OFF{r});

        [tON, xON, Fs_ON_estimado_Hz, N_ON_original] = ...
            leer_csv_rigol_terreno( ...
            archivos_ON{r}, ...
            parametros.Fs_configurada_Hz);

        [tOFF, xOFF, Fs_OFF_estimado_Hz, N_OFF_original] = ...
            leer_csv_rigol_terreno( ...
            archivos_OFF{r}, ...
            parametros.Fs_configurada_Hz);

        xON = xON(:);
        xOFF = xOFF(:);

        N_usado = min(numel(xON), numel(xOFF));

        tON = tON(1:N_usado);
        tOFF = tOFF(1:N_usado);

        xON = xON(1:N_usado);
        xOFF = xOFF(1:N_usado);

        duracion_ON_s = tON(end) - tON(1);
        duracion_OFF_s = tOFF(end) - tOFF(1);

        if duracion_ON_s <= 0 || ~isfinite(duracion_ON_s)
            duracion_ON_s = (N_usado - 1)/parametros.Fs_configurada_Hz;
        end

        if duracion_OFF_s <= 0 || ~isfinite(duracion_OFF_s)
            duracion_OFF_s = (N_usado - 1)/parametros.Fs_configurada_Hz;
        end

        Fs_usada_Hz = parametros.Fs_configurada_Hz;

        xON = xON - mean(xON, 'omitnan');
        xOFF = xOFF - mean(xOFF, 'omitnan');

        xON(~isfinite(xON)) = 0;
        xOFF(~isfinite(xOFF)) = 0;

        switch char(metodo_actual.nombre)

            case 'Periodogram'

                nfft = N_usado;

                [Pxx_ON, fON_Hz] = periodogram( ...
                    xON, ...
                    rectwin(N_usado), ...
                    nfft, ...
                    Fs_usada_Hz, ...
                    'psd');

                [Pxx_OFF, fOFF_Hz] = periodogram( ...
                    xOFF, ...
                    rectwin(N_usado), ...
                    nfft, ...
                    Fs_usada_Hz, ...
                    'psd');

                parametro_1 = nfft;
                parametro_2 = NaN;
                df_Hz = Fs_usada_Hz/nfft;

            case 'Welch'

                if N_usado < parametros.Nseg_welch
                    error( ...
                        'La repeticion %d contiene menos muestras que Nseg_welch = %d.', ...
                        r, ...
                        parametros.Nseg_welch);
                end

                Nseg = min(parametros.Nseg_welch, N_usado);
                noverlap = floor(parametros.fraccion_solapamiento_welch*Nseg);

                if noverlap >= Nseg
                    noverlap = Nseg - 1;
                end

                nfft = Nseg;
                ventana_welch = hann(Nseg, 'periodic');

                [Pxx_ON, fON_Hz] = pwelch( ...
                    xON, ...
                    ventana_welch, ...
                    noverlap, ...
                    nfft, ...
                    Fs_usada_Hz, ...
                    'onesided');

                [Pxx_OFF, fOFF_Hz] = pwelch( ...
                    xOFF, ...
                    ventana_welch, ...
                    noverlap, ...
                    nfft, ...
                    Fs_usada_Hz, ...
                    'onesided');

                parametro_1 = Nseg;
                parametro_2 = noverlap;
                df_Hz = Fs_usada_Hz/nfft;

            case 'Multitaper'

                [Pxx_ON, fON_Hz] = pmtm( ...
                    xON, ...
                    parametros.NW_multitaper, ...
                    parametros.NFFT_multitaper, ...
                    Fs_usada_Hz);

                [Pxx_OFF, fOFF_Hz] = pmtm( ...
                    xOFF, ...
                    parametros.NW_multitaper, ...
                    parametros.NFFT_multitaper, ...
                    Fs_usada_Hz);

                parametro_1 = parametros.NW_multitaper;
                parametro_2 = parametros.NFFT_multitaper;
                df_Hz = Fs_usada_Hz/parametros.NFFT_multitaper;

            otherwise

                error('Metodo no reconocido.');
        end

        fON_Hz = fON_Hz(:);
        fOFF_Hz = fOFF_Hz(:);

        PSD_ON_dB = 10*log10(Pxx_ON(:) + eps);
        PSD_OFF_dB = 10*log10(Pxx_OFF(:) + eps);

        if isempty(f_ref_Hz)

            f_ref_Hz = fON_Hz;

            PSD_ON_mat_dB = nan(numel(f_ref_Hz), nRep);
            PSD_OFF_mat_dB = nan(numel(f_ref_Hz), nRep);
        end

        PSD_ON_mat_dB(:, r) = interp1( ...
            fON_Hz, ...
            PSD_ON_dB, ...
            f_ref_Hz, ...
            'linear', ...
            NaN);

        PSD_OFF_mat_dB(:, r) = interp1( ...
            fOFF_Hz, ...
            PSD_OFF_dB, ...
            f_ref_Hz, ...
            'linear', ...
            NaN);

        error_Fs_ON_pct = ...
            abs(Fs_ON_estimado_Hz - parametros.Fs_configurada_Hz) / ...
            parametros.Fs_configurada_Hz * 100;

        error_Fs_OFF_pct = ...
            abs(Fs_OFF_estimado_Hz - parametros.Fs_configurada_Hz) / ...
            parametros.Fs_configurada_Hz * 100;

        fila_info = table( ...
            string(metodo_actual.nombre_visible), ...
            string(metodo_actual.modo_evaluacion), ...
            r, ...
            string(archivos_ON{r}), ...
            string(archivos_OFF{r}), ...
            N_ON_original, ...
            N_OFF_original, ...
            N_usado, ...
            duracion_ON_s, ...
            duracion_OFF_s, ...
            Fs_ON_estimado_Hz, ...
            Fs_OFF_estimado_Hz, ...
            Fs_usada_Hz, ...
            error_Fs_ON_pct, ...
            error_Fs_OFF_pct, ...
            parametro_1, ...
            parametro_2, ...
            df_Hz, ...
            'VariableNames', { ...
            'metodo', ...
            'modo_evaluacion', ...
            'repeticion', ...
            'archivo_ON', ...
            'archivo_OFF', ...
            'N_ON_original', ...
            'N_OFF_original', ...
            'N_usado', ...
            'duracion_ON_s', ...
            'duracion_OFF_s', ...
            'Fs_ON_estimado_Hz', ...
            'Fs_OFF_estimado_Hz', ...
            'Fs_usada_Hz', ...
            'error_Fs_ON_pct', ...
            'error_Fs_OFF_pct', ...
            'parametro_1', ...
            'parametro_2', ...
            'df_Hz'});

        info_repeticiones = [info_repeticiones; fila_info]; %#ok<AGROW>

        fprintf('N usado       = %d muestras\n', N_usado);
        fprintf('Fs usada      = %.6f MSa/s\n', Fs_usada_Hz/1e6);
        fprintf('df aproximada = %.6f Hz\n', df_Hz);
    end

    PSD_ON_prom_dB = mean(PSD_ON_mat_dB, 2, 'omitnan');
    PSD_OFF_prom_dB = mean(PSD_OFF_mat_dB, 2, 'omitnan');

    % Misma logica usada en la etapa individual:
    % cada repeticion ON se compara contra el OFF promedio.
    PSD_OFF_ref_dB = repmat(PSD_OFF_prom_dB, 1, nRep);
    score_mat_dB = PSD_ON_mat_dB - PSD_OFF_ref_dB;

    score_prom_dB = mean(score_mat_dB, 2, 'omitnan');

    idx_banda = ...
        f_ref_Hz >= parametros.fmin_Hz & ...
        f_ref_Hz <= parametros.fmax_Hz;

    f_banda_Hz = f_ref_Hz(idx_banda);
    PSD_ON_banda_dB = PSD_ON_prom_dB(idx_banda);
    PSD_OFF_banda_dB = PSD_OFF_prom_dB(idx_banda);
    score_banda_dB = score_prom_dB(idx_banda);
    score_banda_reps_dB = score_mat_dB(idx_banda, :);

    idx_validos = ...
        isfinite(f_banda_Hz) & ...
        isfinite(PSD_ON_banda_dB) & ...
        isfinite(PSD_OFF_banda_dB) & ...
        isfinite(score_banda_dB);

    f_banda_Hz = f_banda_Hz(idx_validos);
    PSD_ON_banda_dB = PSD_ON_banda_dB(idx_validos);
    PSD_OFF_banda_dB = PSD_OFF_banda_dB(idx_validos);
    score_banda_dB = score_banda_dB(idx_validos);
    score_banda_reps_dB = score_banda_reps_dB(idx_validos, :);

    tabla_score = table( ...
        f_banda_Hz(:)/1e3, ...
        PSD_ON_banda_dB(:), ...
        PSD_OFF_banda_dB(:), ...
        score_banda_dB(:), ...
        'VariableNames', { ...
        'f_kHz', ...
        'PSD_ON_prom_dB', ...
        'PSD_OFF_prom_dB', ...
        'score_prom_dB'});

    for r = 1:nRep
        tabla_score.(sprintf('score_rep%d_dB', r)) = score_banda_reps_dB(:, r);
    end

    resultado = struct();

    resultado.metodo = metodo_actual.nombre_visible;
    resultado.rol = metodo_actual.rol;
    resultado.modo_evaluacion = metodo_actual.modo_evaluacion;

    resultado.f_ref_Hz = f_ref_Hz;
    resultado.PSD_ON_mat_dB = PSD_ON_mat_dB;
    resultado.PSD_OFF_mat_dB = PSD_OFF_mat_dB;
    resultado.PSD_ON_prom_dB = PSD_ON_prom_dB;
    resultado.PSD_OFF_prom_dB = PSD_OFF_prom_dB;
    resultado.score_mat_dB = score_mat_dB;
    resultado.score_prom_dB = score_prom_dB;

    resultado.f_banda_Hz = f_banda_Hz;
    resultado.f_banda_kHz = f_banda_Hz/1e3;
    resultado.PSD_ON_banda_dB = PSD_ON_banda_dB;
    resultado.PSD_OFF_banda_dB = PSD_OFF_banda_dB;
    resultado.score_banda_dB = score_banda_dB;
    resultado.score_banda_reps_dB = score_banda_reps_dB;

    resultado.tabla_score = tabla_score;
    resultado.info_repeticiones = info_repeticiones;
end

function tabla_comparativa = evaluar_frecuencias_leds( ...
    resultado, ...
    leds, ...
    metodo_actual, ...
    nombre_punto, ...
    parametros)

    nLED = height(leds);
    nRep = size(resultado.score_banda_reps_dB, 2);

    punto = strings(nLED, 1);
    metodo = strings(nLED, 1);
    rol_metodo = strings(nLED, 1);
    modo_evaluacion = strings(nLED, 1);
    led_evaluado = strings(nLED, 1);
    tipo_led = strings(nLED, 1);

    f_ref_kHz = nan(nLED, 1);
    f_evaluada_kHz = nan(nLED, 1);
    delta_kHz = nan(nLED, 1);
    semiancho_busqueda_kHz = nan(nLED, 1);

    score_dB = nan(nLED, 1);
    ON_prom_dB = nan(nLED, 1);
    OFF_prom_dB = nan(nLED, 1);

    rep_0dB = zeros(nLED, 1);
    rep_3dB = zeros(nLED, 1);
    rep_total = repmat(nRep, nLED, 1);

    criterio_dB = repmat(parametros.criterio_dB, nLED, 1);

    supera_3dB = strings(nLED, 1);
    interpretacion = strings(nLED, 1);

    score_rep1_dB = nan(nLED, 1);
    score_rep2_dB = nan(nLED, 1);
    score_rep3_dB = nan(nLED, 1);

    for i = 1:nLED

        f_ref_Hz = leds.f_ref_kHz(i)*1e3;

        idx_local = ...
            resultado.f_banda_Hz >= f_ref_Hz - metodo_actual.semiancho_busqueda_Hz & ...
            resultado.f_banda_Hz <= f_ref_Hz + metodo_actual.semiancho_busqueda_Hz & ...
            isfinite(resultado.score_banda_dB);

        idx_local_abs = find(idx_local);

        if isempty(idx_local_abs)

            warning( ...
                'No hay datos en la ventana local de %s.', ...
                leds.led(i));

            continue;
        end

        [score_maximo, idx_rel] = max(resultado.score_banda_dB(idx_local_abs));

        idx_detectado = idx_local_abs(idx_rel);

        f_evaluada_Hz = resultado.f_banda_Hz(idx_detectado);

        idx_rep = ...
            resultado.f_banda_Hz >= f_evaluada_Hz - parametros.ventana_repetibilidad_Hz & ...
            resultado.f_banda_Hz <= f_evaluada_Hz + parametros.ventana_repetibilidad_Hz;

        score_reps = nan(1, nRep);

        for r = 1:nRep

            score_temp = resultado.score_banda_reps_dB(idx_rep, r);
            score_temp = score_temp(isfinite(score_temp));

            if isempty(score_temp)
                score_reps(r) = NaN;
            else
                score_reps(r) = max(score_temp);
            end
        end

        punto(i) = nombre_punto;
        metodo(i) = metodo_actual.nombre_visible;
        rol_metodo(i) = metodo_actual.rol;
        modo_evaluacion(i) = metodo_actual.modo_evaluacion;
        led_evaluado(i) = leds.led(i);
        tipo_led(i) = leds.tipo(i);

        f_ref_kHz(i) = leds.f_ref_kHz(i);
        f_evaluada_kHz(i) = f_evaluada_Hz/1e3;
        delta_kHz(i) = f_evaluada_kHz(i) - f_ref_kHz(i);
        semiancho_busqueda_kHz(i) = metodo_actual.semiancho_busqueda_Hz/1e3;

        score_dB(i) = score_maximo;
        ON_prom_dB(i) = resultado.PSD_ON_banda_dB(idx_detectado);
        OFF_prom_dB(i) = resultado.PSD_OFF_banda_dB(idx_detectado);

        rep_0dB(i) = sum(score_reps > 0);
        rep_3dB(i) = sum(score_reps >= parametros.criterio_dB);

        if nRep >= 1
            score_rep1_dB(i) = score_reps(1);
        end

        if nRep >= 2
            score_rep2_dB(i) = score_reps(2);
        end

        if nRep >= 3
            score_rep3_dB(i) = score_reps(3);
        end

        if score_dB(i) >= parametros.criterio_dB && ...
                rep_3dB(i) >= parametros.umbral_repeticiones

            supera_3dB(i) = "Si";
            interpretacion(i) = "Confirmado";

        elseif score_dB(i) >= parametros.criterio_dB && ...
                rep_3dB(i) < parametros.umbral_repeticiones

            supera_3dB(i) = "No";
            interpretacion(i) = "Indicio parcial";

        elseif score_dB(i) > 0

            supera_3dB(i) = "No";
            interpretacion(i) = "Indicio debil";

        else

            supera_3dB(i) = "No";
            interpretacion(i) = "No confirmado";
        end
    end

    tabla_comparativa = table( ...
        punto, ...
        metodo, ...
        rol_metodo, ...
        modo_evaluacion, ...
        led_evaluado, ...
        tipo_led, ...
        f_ref_kHz, ...
        f_evaluada_kHz, ...
        delta_kHz, ...
        semiancho_busqueda_kHz, ...
        score_dB, ...
        ON_prom_dB, ...
        OFF_prom_dB, ...
        rep_0dB, ...
        rep_3dB, ...
        rep_total, ...
        criterio_dB, ...
        supera_3dB, ...
        interpretacion, ...
        score_rep1_dB, ...
        score_rep2_dB, ...
        score_rep3_dB, ...
        'VariableNames', { ...
        'punto', ...
        'metodo', ...
        'rol_metodo', ...
        'modo_evaluacion', ...
        'led_evaluado', ...
        'tipo_led', ...
        'f_ref_kHz', ...
        'f_evaluada_kHz', ...
        'delta_kHz', ...
        'semiancho_busqueda_kHz', ...
        'score_dB', ...
        'ON_prom_dB', ...
        'OFF_prom_dB', ...
        'rep_0dB', ...
        'rep_3dB', ...
        'rep_total', ...
        'criterio_dB', ...
        'supera_3dB', ...
        'interpretacion', ...
        'score_rep1_dB', ...
        'score_rep2_dB', ...
        'score_rep3_dB'});
end

