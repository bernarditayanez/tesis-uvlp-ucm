function generar_figura_global( ...
    tabla_global, ...
    leds, ...
    metodos, ...
    carpeta_salida_base, ...
    parametros)

    nLED = height(leds);
    nMetodos = numel(metodos);

    matriz_scores = nan(nLED, nMetodos);

    for i = 1:nLED

        for m = 1:nMetodos

            idx = ...
                tabla_global.led_evaluado == leds.led(i) & ...
                tabla_global.metodo == metodos(m).nombre_visible;

            if any(idx)

                idx_primero = find(idx, 1, 'first');

                matriz_scores(i, m) = tabla_global.score_dB(idx_primero);
            end
        end
    end

    matriz_scores_grafico = matriz_scores;
    matriz_scores_grafico(matriz_scores_grafico < 0) = 0;

    fig = figure( ...
        'Color', 'w', ...
        'Position', [100 100 1350 760]);

    bar(matriz_scores_grafico);

    hold on;
    grid on;
    box on;

    yline( ...
        parametros.criterio_dB, ...
        '--', ...
        sprintf('Criterio %.1f dB', parametros.criterio_dB), ...
        'LineWidth', 1.1, ...
        'HandleVisibility', 'off');

    xlabel('LED evaluado');
    ylabel('Score local ON-OFF [dB]');

    title( ...
        'P2 - Comparativa global LED 1, LED 2 y LED 3', ...
        'Interpreter', 'none');

    xticks(1:nLED);
    xticklabels(leds.led);

    leyenda = strings(1, nMetodos);

    for m = 1:nMetodos
        leyenda(m) = metodos(m).nombre_visible;
    end

    legend(leyenda, 'Location', 'best');

    ylim([ ...
        0, ...
        max(parametros.criterio_dB + 1.5, max(matriz_scores_grafico(:)) + 3)]);

    guardar_figura_png( ...
        fig, ...
        fullfile( ...
        carpeta_salida_base, ...
        'figura_resumen_global_scores_P2_LEDs_1_2_3.png'));
end

function generar_figuras_comparativas_entre_metodos( ...
    resultados_metodos, ...
    tabla_global, ...
    leds, ...
    carpeta_salida_base, ...
    nombre_comparativa, ...
    parametros)

    if isempty(resultados_metodos)
        warning('No hay resultados disponibles para generar figuras comparativas entre metodos.');
        return;
    end

    offsets_cascada = [0, 32, 65];

    if numel(offsets_cascada) < numel(resultados_metodos)
        offsets_cascada = linspace( ...
            0, ...
            32*(numel(resultados_metodos)-1), ...
            numel(resultados_metodos));
    end

    for iLED = 1:height(leds)

        led_actual = leds.led(iLED);
        f_ref_kHz = leds.f_ref_kHz(iLED);

        idx_led_global = tabla_global.led_evaluado == led_actual;

        if ~any(idx_led_global)
            continue;
        end

        f_eval_prom_kHz = mean( ...
            tabla_global.f_evaluada_kHz(idx_led_global), ...
            'omitnan');

        if ~isfinite(f_eval_prom_kHz)
            f_eval_prom_kHz = f_ref_kHz;
        end

        f_centro_kHz = mean([f_ref_kHz, f_eval_prom_kHz], 'omitnan');
        semiancho_kHz = max(parametros.ancho_zoom_Hz/1e3, 2.0);

        xmin_kHz = f_centro_kHz - semiancho_kHz;
        xmax_kHz = f_centro_kHz + semiancho_kHz;

        %% Figura comparativa tipo cascada

        fig = figure( ...
            'Color', 'w', ...
            'Position', [100 100 1600 850]);

        hold on;
        grid on;
        box on;

        h_lineas = gobjects(1, numel(resultados_metodos));

        for m = 1:numel(resultados_metodos)

            resultado_m = resultados_metodos(m).resultado;
            metodo_m = resultados_metodos(m).metodo;
            tabla_m = resultados_metodos(m).tabla_comparativa;

            idx_zoom = ...
                resultado_m.f_banda_kHz >= xmin_kHz & ...
                resultado_m.f_banda_kHz <= xmax_kHz;

            if ~any(idx_zoom)
                continue;
            end

            offset_m = offsets_cascada(m);

            h_lineas(m) = plot( ...
                resultado_m.f_banda_kHz(idx_zoom), ...
                resultado_m.score_banda_dB(idx_zoom) + offset_m, ...
                'LineWidth', 1.25, ...
                'DisplayName', char(metodo_m.nombre_visible));

            yline(offset_m, ':', 'HandleVisibility', 'off');

            yline( ...
                offset_m + parametros.criterio_dB, ...
                '--', ...
                'HandleVisibility', 'off');

            text( ...
                xmin_kHz + 0.02*(xmax_kHz - xmin_kHz), ...
                offset_m + 1.2, ...
                char(metodo_m.nombre_visible), ...
                'FontWeight', 'bold', ...
                'FontSize', 11, ...
                'HorizontalAlignment', 'left', ...
                'VerticalAlignment', 'bottom', ...
                'BackgroundColor', 'w', ...
                'Margin', 0.5, ...
                'Interpreter', 'none');

            idx_fila = tabla_m.led_evaluado == led_actual;

            if any(idx_fila)

                fila = tabla_m(find(idx_fila, 1, 'first'), :);

                x_eval = fila.f_evaluada_kHz;
                y_eval = fila.score_dB + offset_m;

                switch char(metodo_m.nombre_visible)

                    case 'Periodograma'
                        marcador = 'o';

                    case 'Welch'
                        marcador = 's';

                    otherwise
                        marcador = '*';
                end

                plot( ...
                    x_eval, ...
                    y_eval, ...
                    marcador, ...
                    'MarkerSize', 9, ...
                    'LineWidth', 1.8, ...
                    'Color', 'k', ...
                    'MarkerFaceColor', 'w', ...
                    'HandleVisibility', 'off');

                text( ...
                    x_eval, ...
                    y_eval + 1.5, ...
                    sprintf('%.3f kHz\n%.2f dB', ...
                    x_eval, ...
                    fila.score_dB), ...
                    'HorizontalAlignment', 'center', ...
                    'VerticalAlignment', 'bottom', ...
                    'FontSize', 8, ...
                    'BackgroundColor', 'w', ...
                    'Margin', 0.5, ...
                    'Interpreter', 'none');
            end
        end

        xline( ...
            f_ref_kHz, ...
            '--', ...
            'LineWidth', 1.2, ...
            'HandleVisibility', 'off');

        yl = ylim;

        text( ...
            f_ref_kHz, ...
            yl(2) - 0.06*(yl(2)-yl(1)), ...
            sprintf('f_{ref} = %.3f kHz', f_ref_kHz), ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'top', ...
            'FontSize', 9, ...
            'FontWeight', 'bold', ...
            'BackgroundColor', 'w', ...
            'Margin', 0.6, ...
            'Interpreter', 'tex');

        xlabel('Frecuencia [kHz]');
        ylabel('Score ON-OFF desplazado [dB]');

        title( ...
            sprintf('%s - %s: cascada de score ON-OFF por metodo', ...
            char(nombre_comparativa), ...
            char(led_actual)), ...
            'Interpreter', 'none');

        xlim([xmin_kHz xmax_kHz]);

        y_max = max(offsets_cascada(1:numel(resultados_metodos))) + 15;
        ylim([-20 y_max]);

        legend( ...
            h_lineas(isgraphics(h_lineas)), ...
            'Location', 'eastoutside');

        guardar_figura_png( ...
            fig, ...
            fullfile( ...
            carpeta_salida_base, ...
            sprintf('figura_%s_%s_comparativa_cascada_metodos.png', ...
            char(nombre_comparativa), ...
            limpiar_nombre(char(led_actual)))));

        %% Figura comparativa local sin desplazamiento

        fig = figure( ...
            'Color', 'w', ...
            'Position', [100 100 1600 850]);

        hold on;
        grid on;
        box on;

        h_lineas = gobjects(1, numel(resultados_metodos));

