                ancho_linea = 1.35;
            end

            h_lineas(m) = plot( ...
                resultado_m.f_banda_kHz(idx_zoom), ...
                resultado_m.score_banda_dB(idx_zoom), ...
                'LineWidth', ancho_linea, ...
                'DisplayName', char(metodo_m.nombre_visible));

            idx_fila = tabla_m.led_evaluado == led_actual;

            if any(idx_fila)

                fila = tabla_m(find(idx_fila, 1, 'first'), :);

                x_eval = fila.f_evaluada_kHz;
                y_eval = fila.score_dB;

                plot( ...
                    x_eval, ...
                    y_eval, ...
                    'o', ...
                    'MarkerSize', 9, ...
                    'LineWidth', 1.8, ...
                    'Color', 'k', ...
                    'MarkerFaceColor', 'w', ...
                    'HandleVisibility', 'off');

                text( ...
                    x_eval, ...
                    y_eval + 0.8, ...
                    sprintf('%.3f kHz\n%.2f dB', ...
                    x_eval, ...
                    fila.score_dB), ...
                    'HorizontalAlignment', 'center', ...
                    'VerticalAlignment', 'bottom', ...
                    'FontSize', 8, ...
                    'BackgroundColor', 'w', ...
                    'Margin', 0.5, ...
                    'Interpreter', 'none');
            end
        end

        yline(0, '--', 'HandleVisibility', 'off');

        yline( ...
            parametros.criterio_dB, ...
            '--', ...
            'LineWidth', 1.1, ...
            'HandleVisibility', 'off');

        xline( ...
            f_ref_kHz, ...
            '--', ...
            'LineWidth', 1.2, ...
            'HandleVisibility', 'off');

        yl = ylim;

        text( ...
            xmax_kHz - 0.02*(xmax_kHz - xmin_kHz), ...
            parametros.criterio_dB + 0.35, ...
            sprintf('Criterio %.1f dB', parametros.criterio_dB), ...
            'HorizontalAlignment', 'right', ...
            'VerticalAlignment', 'bottom', ...
            'FontSize', 9, ...
            'BackgroundColor', 'w', ...
            'Margin', 0.5, ...
            'Interpreter', 'none');

        text( ...
            xmax_kHz - 0.02*(xmax_kHz - xmin_kHz), ...
            0 + 0.35, ...
            '0 dB', ...
            'HorizontalAlignment', 'right', ...
            'VerticalAlignment', 'bottom', ...
            'FontSize', 9, ...
            'BackgroundColor', 'w', ...
            'Margin', 0.5, ...
            'Interpreter', 'none');

        text( ...
            f_ref_kHz, ...
            yl(2) - 0.06*(yl(2)-yl(1)), ...
            sprintf('f_{ref} = %.3f kHz', f_ref_kHz), ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'top', ...
            'FontSize', 9, ...
            'FontWeight', 'bold', ...
            'BackgroundColor', 'w', ...
            'Margin', 0.6, ...
            'Interpreter', 'tex');

        xlabel('Frecuencia [kHz]');
        ylabel('Score ON - OFF [dB]');

        title( ...
            sprintf('%s - %s: comparativa local de score por metodo', ...
            char(nombre_comparativa), ...
            char(led_actual)), ...
            'Interpreter', 'none');

        xlim([xmin_kHz xmax_kHz]);

        legend( ...
            h_lineas(isgraphics(h_lineas)), ...
            'Location', 'eastoutside');

        guardar_figura_png( ...
            fig, ...
            fullfile( ...
            carpeta_salida_base, ...
            sprintf('figura_%s_%s_comparativa_local_metodos.png', ...
            char(nombre_comparativa), ...
            limpiar_nombre(char(led_actual)))));
    end
end

function [t, y, Fs_estimado_Hz, N_original] = ...
    leer_csv_rigol_terreno(nombre_archivo, Fs_default)

    M = readmatrix(nombre_archivo);

    if isempty(M)
        error('El archivo esta vacio:\n%s', nombre_archivo);
    end

    columnas_validas = [];

    for c = 1:size(M, 2)

        if sum(isfinite(M(:, c))) > 10
            columnas_validas = [columnas_validas, c]; %#ok<AGROW>
        end
    end

    if isempty(columnas_validas)

        error( ...
            'No se detectaron columnas numericas validas en:\n%s', ...
            nombre_archivo);
    end

    M = M(:, columnas_validas);

    t = [];
    y = [];
    Fs_estimado_Hz = Fs_default;

    if size(M, 2) >= 2

        for c = 1:(size(M, 2) - 1)

            t_cand = M(:, c);
            y_cand = M(:, c + 1);

            idx_validos = isfinite(t_cand) & isfinite(y_cand);

            t_temp = t_cand(idx_validos);
            y_temp = y_cand(idx_validos);

            t_temp = t_temp(:);
            y_temp = y_temp(:);

            if numel(y_temp) < 10
                continue;
            end

            duracion_s = t_temp(end) - t_temp(1);

            if duracion_s <= 0 || ~isfinite(duracion_s)
                continue;
            end

            Fs_temp_Hz = (numel(t_temp) - 1)/duracion_s;

            error_Fs_pct = abs(Fs_temp_Hz - Fs_default)/Fs_default*100;

            if error_Fs_pct <= 20 && std(y_temp, 'omitnan') > 0

                t = t_temp;
                y = y_temp;
                Fs_estimado_Hz = Fs_temp_Hz;
                N_original = numel(y);
                return;
            end
        end
    end

    y = M(:, end);
    y = y(isfinite(y));
    y = y(:);

    if numel(y) < 10

        error( ...
            'El archivo contiene muy pocas muestras validas:\n%s', ...
            nombre_archivo);
    end

    t = (0:numel(y)-1)'/Fs_default;
    Fs_estimado_Hz = Fs_default;
    N_original = numel(y);
end

