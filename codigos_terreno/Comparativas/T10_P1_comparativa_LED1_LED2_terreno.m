            'EdgeColor', color_borde, ...
            'LineWidth', 0.8);

        text( ...
            ax, ...
            x + ancho_columnas(c)/2, ...
            y0 - alto_encabezado/2, ...
            nombres{c}, ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'FontWeight', 'bold', ...
            'FontSize', 9, ...
            'Interpreter', 'none');

        x = x + ancho_columnas(c);
    end

    for i = 1:nFilas

        y = y0 - alto_encabezado - i*alto_fila;

        if mod(i, 2) == 0
            color_fila = color_fila_2;
        else
            color_fila = color_fila_1;
        end

        x = x0;

        for c = 1:nColumnas

            rectangle( ...
                ax, ...
                'Position', [x, y, ancho_columnas(c), alto_fila], ...
                'FaceColor', color_fila, ...
                'EdgeColor', [0.88 0.88 0.88], ...
                'LineWidth', 0.5);

            text( ...
                ax, ...
                x + ancho_columnas(c)/2, ...
                y + alto_fila/2, ...
                datos{i, c}, ...
                'HorizontalAlignment', 'center', ...
                'VerticalAlignment', 'middle', ...
                'FontSize', 9, ...
                'Interpreter', 'none');

            x = x + ancho_columnas(c);
        end
    end

    drawnow;

    print( ...
        fig, ...
        archivo_png, ...
        '-dpng', ...
        '-r300');
end

function datos = formatear_tabla_para_figura(tabla)

    nFilas = height(tabla);
    nColumnas = width(tabla);

    datos = cell(nFilas, nColumnas);
    nombres = tabla.Properties.VariableNames;

    for c = 1:nColumnas

        nombre = nombres{c};
        columna = tabla.(nombre);

        for i = 1:nFilas

            if iscell(columna)
                valor = columna{i};
            else
                valor = columna(i);
            end

            if isnumeric(valor)

                if isnan(valor)

                    texto = '';

                elseif contains(nombre, 'kHz', 'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains(nombre, 'Hz', 'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains(nombre, 'dB', 'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains(nombre, 'rep', 'IgnoreCase', true)

                    texto = sprintf('%.0f', valor);

                elseif contains(nombre, 'criterio', 'IgnoreCase', true)

                    texto = sprintf('%.1f', valor);

                else

                    texto = sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor
                    texto = 'Si';
                else
                    texto = 'No';
                end

            elseif isstring(valor)

                texto = char(valor);

            elseif ischar(valor)

                texto = valor;

            else

                texto = char(string(valor));
            end

            datos{i, c} = texto;
        end
    end
end

function nombre_limpio = limpiar_nombre(nombre)

    nombre_limpio = lower(nombre);
    nombre_limpio = strrep(nombre_limpio, ' ', '_');
    nombre_limpio = strrep(nombre_limpio, '/', '_');
    nombre_limpio = strrep(nombre_limpio, '\', '_');
    nombre_limpio = strrep(nombre_limpio, ':', '_');
end

function crear_figura_score_local_2D_terreno( ...
    f_per_kHz, score_per_dB, ...
    f_wel_kHz, score_wel_dB, ...
    f_mt_kHz, score_mt_dB, ...
    fc_ref_kHz, fc_promedio_kHz, ...
    fc_metodos_kHz, score_metodos_dB, ...
    metodos, criterio_dB, ...
    fmin_local_kHz, fmax_local_kHz, ...
    punto, led_actual, nombre_comparativa, carpeta_salida)

    fig = figure('Color','w','Position',[100 100 1600 820]);
    hold on;
    grid on;
    box on;

    idx_per = f_per_kHz >= fmin_local_kHz & f_per_kHz <= fmax_local_kHz;
    idx_wel = f_wel_kHz >= fmin_local_kHz & f_wel_kHz <= fmax_local_kHz;
    idx_mt  = f_mt_kHz  >= fmin_local_kHz & f_mt_kHz  <= fmax_local_kHz;

    plot(f_per_kHz(idx_per), score_per_dB(idx_per), ...
        'LineWidth', 0.85, ...
        'DisplayName','Periodograma');

    plot(f_wel_kHz(idx_wel), score_wel_dB(idx_wel), ...
        'LineWidth', 1.35, ...
        'DisplayName','Welch');

    plot(f_mt_kHz(idx_mt), score_mt_dB(idx_mt), ...
        'LineWidth', 1.35, ...
        'DisplayName','Multitaper');

    plot(fc_metodos_kHz, score_metodos_dB, 'ko', ...
        'MarkerSize', 8.5, ...
        'LineWidth', 1.6, ...
        'MarkerFaceColor','w', ...
        'DisplayName','Maximos locales');

    xline(fc_ref_kHz, '--', ...
        'LineWidth', 1.2, ...
        'HandleVisibility','off');

    yline(criterio_dB, '--', ...
        'LineWidth', 1.1, ...
        'HandleVisibility','off');

    yline(0, '--', ...
        'LineWidth', 1.0, ...
        'HandleVisibility','off');

    xlabel('Frecuencia [kHz]');
    ylabel('Score ON - OFF [dB]');

    title(sprintf('%s - %s: comparativa local de score por metodo', ...
        nombre_comparativa, led_actual), ...
        'Interpreter','none');

    xlim([fmin_local_kHz fmax_local_kHz]);

    y_min = min([score_per_dB(idx_per); score_wel_dB(idx_wel); score_mt_dB(idx_mt)], [], 'omitnan');
    y_max = max([score_per_dB(idx_per); score_wel_dB(idx_wel); score_mt_dB(idx_mt)], [], 'omitnan');

    if isempty(y_min) || isempty(y_max) || isnan(y_min) || isnan(y_max)
        ylim([-15 20]);
    else
        ylim([min(-6, y_min - 2), max(6, y_max + 4)]);
    end

    yl = ylim;

    text(fc_ref_kHz, ...
        yl(2) - 0.06*(yl(2)-yl(1)), ...
        sprintf('f_{ref} = %.3f kHz', fc_ref_kHz), ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','top', ...
        'FontSize',9, ...
        'FontWeight','bold', ...
        'BackgroundColor','w', ...
        'Margin',0.6, ...
        'Interpreter','tex');

    text(fmax_local_kHz - 0.02*(fmax_local_kHz - fmin_local_kHz), ...
        criterio_dB + 0.35, ...
        sprintf('Criterio %.1f dB', criterio_dB), ...
        'HorizontalAlignment','right', ...
        'VerticalAlignment','bottom', ...
        'FontSize',9, ...
        'BackgroundColor','w', ...
        'Margin',0.5, ...
        'Interpreter','none');

    text(fmax_local_kHz - 0.02*(fmax_local_kHz - fmin_local_kHz), ...
        0 + 0.35, ...
        '0 dB', ...
        'HorizontalAlignment','right', ...
        'VerticalAlignment','bottom', ...
        'FontSize',9, ...
        'BackgroundColor','w', ...
        'Margin',0.5, ...
        'Interpreter','none');

    for i = 1:numel(metodos)

        if ~isfinite(fc_metodos_kHz(i)) || ~isfinite(score_metodos_dB(i))
            continue;
        end

        text(fc_metodos_kHz(i), score_metodos_dB(i) + 0.75, ...
            sprintf('%.3f kHz\n%.2f dB', ...
            fc_metodos_kHz(i), ...
            score_metodos_dB(i)), ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','bottom', ...
            'FontSize',8, ...
            'BackgroundColor','w', ...
            'Margin',0.5, ...
            'Interpreter','none');
    end

    lgd = legend('Location','eastoutside');
    lgd.Box = 'on';

    nombre_led_archivo = strrep(led_actual, ' ', '_');

    archivo_png = fullfile(carpeta_salida, ...
        sprintf('figura_local_%s_%s_score_metodos_2D.png', ...
        nombre_comparativa, ...
        nombre_led_archivo));

    archivo_fig = fullfile(carpeta_salida, ...
        sprintf('figura_local_%s_%s_score_metodos_2D.fig', ...
        nombre_comparativa, ...
        nombre_led_archivo));

    exportgraphics(fig, archivo_png, 'Resolution', 300);
    savefig(fig, archivo_fig);
end

