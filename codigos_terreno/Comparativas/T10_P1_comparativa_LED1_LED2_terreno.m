function generar_figuras_locales_tipo_laboratorio_terreno( ...
    resultados_metodos, ...
    tabla_global, ...
    leds, ...
    nombre_punto, ...
    nombre_comparativa, ...
    carpeta_salida_base, ...
    parametros)

    % Genera las figuras tipo laboratorio usando las curvas ya calculadas.
    % No crea carpetas nuevas: guarda directamente en carpeta_salida_base.

    ancho_grafica_local_kHz = parametros.ancho_grafica_tipo_laboratorio_kHz;

    nombres_metodos_tabla = ["Periodograma"; "Welch"; "Multitaper"];
    nombres_metodos_curvas = ["Periodograma"; "Welch"; "Multitaper local"];

    for i_led = 1:height(leds)

        led_actual = leds.led(i_led);
        fc_ref_kHz = leds.f_ref_kHz(i_led);

        fc_metodos_kHz = nan(3, 1);
        score_metodos_dB = nan(3, 1);

        f_per_kHz = [];
        score_per_dB = [];
        f_wel_kHz = [];
        score_wel_dB = [];
        f_mt_kHz = [];
        score_mt_dB = [];

        for i_met = 1:3

            metodo_busqueda = nombres_metodos_tabla(i_met);

            idx_tabla = ...
                tabla_global.led_evaluado == led_actual & ...
                tabla_global.metodo == metodo_busqueda;

            if any(idx_tabla)

                idx_primero = find(idx_tabla, 1, 'first');

                fc_metodos_kHz(i_met) = tabla_global.f_evaluada_kHz(idx_primero);
                score_metodos_dB(i_met) = tabla_global.score_dB(idx_primero);
