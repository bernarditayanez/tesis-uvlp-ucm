        fmin_local_kHz = fc_ref_kHz - ancho_grafica_local_kHz;
        fmax_local_kHz = fc_ref_kHz + ancho_grafica_local_kHz;

        crear_figura_score_local_2D_terreno( ...
            f_per_kHz, ...
            score_per_dB, ...
            f_wel_kHz, ...
            score_wel_dB, ...
            f_mt_kHz, ...
            score_mt_dB, ...
            fc_ref_kHz, ...
            fc_promedio_kHz, ...
            fc_metodos_kHz, ...
            score_metodos_dB, ...
            cellstr(nombres_metodos_curvas), ...
            parametros.criterio_dB, ...
            fmin_local_kHz, ...
            fmax_local_kHz, ...
            char(nombre_punto), ...
            char(led_actual), ...
            char(nombre_comparativa), ...
            carpeta_salida_base);

        crear_figura_score_cascada_2D_terreno( ...
            f_per_kHz, ...
            score_per_dB, ...
            f_wel_kHz, ...
            score_wel_dB, ...
            f_mt_kHz, ...
            score_mt_dB, ...
            fc_ref_kHz, ...
            fc_promedio_kHz, ...
            fc_metodos_kHz, ...
            score_metodos_dB, ...
            parametros.criterio_dB, ...
            fmin_local_kHz, ...
            fmax_local_kHz, ...
            char(nombre_punto), ...
