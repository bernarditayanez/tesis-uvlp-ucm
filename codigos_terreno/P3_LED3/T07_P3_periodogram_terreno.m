fc_detectada_kHz = f_banda_kHz(idx_final);
score_detectado_dB = score_prom_dB(idx_final);

ON_detectado_dB = PSD_ON_prom_dB(idx_final);
OFF_detectado_dB = PSD_OFF_prom_dB(idx_final);

rep_0dB_detectado = rep_0dB(idx_final);
rep_3dB_detectado = rep_3dB(idx_final);

if score_detectado_dB >= criterio_dB && ...
        rep_3dB_detectado >= umbral_repeticiones

    supera_3dB = "Si";
else
    supera_3dB = "No";
end

