%% T07_P3_periodogram_terreno.m
% Analisis Periodograma - P3 / LED terreno 3
%
% Antes de ejecutar este script, modificar las variables carpeta_ON
% y carpeta_OFF con las rutas locales donde se encuentran los archivos .csv
% de la medicion correspondiente.
%
% La carpeta_ON debe contener los archivos ON_P3_REP*.csv indicados
% en la lista archivos_ON.
% La carpeta_OFF debe contener los archivos OFF comunes indicados
% en la lista archivos_OFF.
%
% Ejemplo:
% carpeta_ON  = 'C:\Users\NombreUsuario\Desktop\Terreno_ON_M3';
% carpeta_OFF = 'C:\Users\NombreUsuario\Desktop\Terreno_OFF';

clear;
clc;
close all;

%% 1. Configuracion

carpeta_base = 'C:\Users\berni\OneDrive\Escritorio\Modulo Prof\Archivos Tesis\Toma de Datos\Pruebas en terreno';

carpeta_ON = fullfile(carpeta_base, 'Terreno_ON_M3');
carpeta_OFF = fullfile(carpeta_base, 'Terreno_OFF');

carpeta_salida = fullfile( ...
    carpeta_base, ...
    'Resultados_Terreno', ...
    'P3_LED3', ...
    '01_Periodogram');

if ~exist(carpeta_salida, 'dir')
    mkdir(carpeta_salida);
end

nombre_punto = "P3";
nombre_led = "LED terreno 3";
nombre_metodo = "Periodograma";

nRep = 3;

archivos_ON = cell(nRep, 1);
archivos_OFF = cell(nRep, 1);

for r = 1:nRep
    archivos_ON{r} = fullfile( ...
        carpeta_ON, ...
        sprintf('ON_P3_REP%d.csv', r));

    archivos_OFF{r} = fullfile( ...
        carpeta_OFF, ...
        sprintf('OFF_REP%d.csv', r));
end

fmin_kHz = 30;
fmax_kHz = 90;

criterio_dB = 3;
umbral_repeticiones = 3;

num_candidatos = 7;
dist_min_candidatos_kHz = 0.3;

Fs_default = 50e6;

Nmax = Inf;
nfft_max = Inf;

fprintf('\n============================================================\n');
fprintf('PUNTO 3 / LED TERRENO 3 - PERIODOGRAMA\n');
fprintf('============================================================\n');
fprintf('Carpeta base:\n%s\n\n', carpeta_base);
fprintf('Carpeta ON:\n%s\n\n', carpeta_ON);
fprintf('Carpeta OFF:\n%s\n\n', carpeta_OFF);
fprintf('Carpeta salida:\n%s\n\n', carpeta_salida);

%% 2. Verificacion de archivos

for r = 1:nRep

    if ~exist(archivos_ON{r}, 'file')
        error( ...
            'No existe el archivo ON de la repeticion %d:\n%s', ...
            r, ...
            archivos_ON{r});
    end

    if ~exist(archivos_OFF{r}, 'file')
        error( ...
            'No existe el archivo OFF de la repeticion %d:\n%s', ...
            r, ...
            archivos_OFF{r});
    end
end

fprintf('Archivos verificados correctamente.\n');

%% 3. Procesamiento por repeticion

f_banda_ref_Hz = [];
f_full_ref_Hz = [];

PSD_ON_mat_dB = [];
PSD_OFF_mat_dB = [];

PSD_ON_full_mat_dB = [];
PSD_OFF_full_mat_dB = [];

info_reps = table();

for r = 1:nRep

    fprintf('\n------------------------------------------------------------\n');
    fprintf('Repeticion %d/%d\n', r, nRep);
    fprintf('ON : %s\n', archivos_ON{r});
    fprintf('OFF: %s\n', archivos_OFF{r});

    [tON, xON, FsON, N_ON_original] = leer_csv_rigol_terreno(archivos_ON{r}, Fs_default);
    [tOFF, xOFF, FsOFF, N_OFF_original] = leer_csv_rigol_terreno(archivos_OFF{r}, Fs_default);

    xON = xON(:);
    xOFF = xOFF(:);

    N_ON = numel(xON);
    N_OFF = numel(xOFF);

    if isfinite(Nmax)
        N_ON_usado = min(N_ON, Nmax);
        N_OFF_usado = min(N_OFF, Nmax);
    else
        N_ON_usado = N_ON;
        N_OFF_usado = N_OFF;
    end

    xON = xON(1:N_ON_usado);
    xOFF = xOFF(1:N_OFF_usado);

    xON = xON - mean(xON, 'omitnan');
    xOFF = xOFF - mean(xOFF, 'omitnan');

    xON(~isfinite(xON)) = 0;
    xOFF(~isfinite(xOFF)) = 0;

    if isfinite(nfft_max)
        nfft_ON = min(N_ON_usado, nfft_max);
        nfft_OFF = min(N_OFF_usado, nfft_max);
    else
        nfft_ON = N_ON_usado;
        nfft_OFF = N_OFF_usado;
    end

    nfft_ON = floor(nfft_ON);
    nfft_OFF = floor(nfft_OFF);

    [P_ON, fON] = periodogram( ...
        xON, ...
        rectwin(N_ON_usado), ...
        nfft_ON, ...
        FsON, ...
        'psd');

    [P_OFF, fOFF] = periodogram( ...
        xOFF, ...
        rectwin(N_OFF_usado), ...
        nfft_OFF, ...
        FsOFF, ...
        'psd');

    PSD_ON_dB = 10*log10(P_ON + eps);
    PSD_OFF_dB = 10*log10(P_OFF + eps);

    if isempty(f_full_ref_Hz)

        f_full_ref_Hz = fON(:);

        PSD_ON_full_mat_dB = nan(numel(f_full_ref_Hz), nRep);
        PSD_OFF_full_mat_dB = nan(numel(f_full_ref_Hz), nRep);
    end

    PSD_ON_full_mat_dB(:, r) = interp1( ...
        fON(:), ...
        PSD_ON_dB(:), ...
        f_full_ref_Hz, ...
        'linear', ...
        NaN);

    PSD_OFF_full_mat_dB(:, r) = interp1( ...
        fOFF(:), ...
        PSD_OFF_dB(:), ...
        f_full_ref_Hz, ...
        'linear', ...
        NaN);

    idx_ON_banda = ...
        fON >= fmin_kHz*1e3 & ...
        fON <= fmax_kHz*1e3;

    idx_OFF_banda = ...
        fOFF >= fmin_kHz*1e3 & ...
        fOFF <= fmax_kHz*1e3;

    fON_banda_Hz = fON(idx_ON_banda);
    fOFF_banda_Hz = fOFF(idx_OFF_banda);

    PSD_ON_banda_dB = PSD_ON_dB(idx_ON_banda);
    PSD_OFF_banda_dB = PSD_OFF_dB(idx_OFF_banda);

    if isempty(f_banda_ref_Hz)

        f_banda_ref_Hz = fON_banda_Hz(:);

        PSD_ON_mat_dB = nan(numel(f_banda_ref_Hz), nRep);
        PSD_OFF_mat_dB = nan(numel(f_banda_ref_Hz), nRep);
    end

    PSD_ON_mat_dB(:, r) = interp1( ...
        fON_banda_Hz, ...
        PSD_ON_banda_dB, ...
        f_banda_ref_Hz, ...
        'linear', ...
        NaN);

    PSD_OFF_mat_dB(:, r) = interp1( ...
        fOFF_banda_Hz, ...
        PSD_OFF_banda_dB, ...
        f_banda_ref_Hz, ...
        'linear', ...
        NaN);

    df_ON_Hz = FsON / nfft_ON;
    df_OFF_Hz = FsOFF / nfft_OFF;

    fila_info = table( ...
        r, ...
        N_ON_original, ...
        N_OFF_original, ...
        N_ON_usado, ...
        N_OFF_usado, ...
        FsON, ...
        FsOFF, ...
        nfft_ON, ...
        nfft_OFF, ...
        df_ON_Hz, ...
        df_OFF_Hz, ...
        'VariableNames', { ...
        'repeticion', ...
        'N_ON_original', ...
        'N_OFF_original', ...
        'N_ON_usado', ...
        'N_OFF_usado', ...
        'Fs_ON_Hz', ...
        'Fs_OFF_Hz', ...
        'nfft_ON', ...
        'nfft_OFF', ...
        'df_ON_Hz', ...
        'df_OFF_Hz'});

    info_reps = [info_reps; fila_info];

    fprintf('N ON original  = %d muestras\n', N_ON_original);
    fprintf('N OFF original = %d muestras\n', N_OFF_original);
    fprintf('N ON usado     = %d muestras\n', N_ON_usado);
    fprintf('N OFF usado    = %d muestras\n', N_OFF_usado);
    fprintf('Fs ON          = %.6f MSa/s\n', FsON/1e6);
    fprintf('Fs OFF         = %.6f MSa/s\n', FsOFF/1e6);
    fprintf('df ON          = %.6f Hz\n', df_ON_Hz);
    fprintf('df OFF         = %.6f Hz\n', df_OFF_Hz);
end

%% 4. Promedios y score ON-OFF

f_banda_kHz = f_banda_ref_Hz / 1e3;

PSD_ON_prom_dB = mean( ...
    PSD_ON_mat_dB, ...
    2, ...
    'omitnan');

PSD_OFF_prom_dB = mean( ...
    PSD_OFF_mat_dB, ...
    2, ...
    'omitnan');

PSD_ON_full_prom_dB = mean( ...
    PSD_ON_full_mat_dB, ...
    2, ...
    'omitnan');

PSD_OFF_full_prom_dB = mean( ...
    PSD_OFF_full_mat_dB, ...
    2, ...
    'omitnan');

score_mat_dB = PSD_ON_mat_dB - PSD_OFF_prom_dB;

score_prom_dB = mean( ...
    score_mat_dB, ...
    2, ...
    'omitnan');

rep_0dB = sum(score_mat_dB > 0, 2);
rep_3dB = sum(score_mat_dB >= criterio_dB, 2);

%% 5. Deteccion de frecuencia propia del Punto 3

[idx_candidatos, ~, ~] = seleccionar_candidatos_globales( ...
    f_banda_kHz, ...
    score_prom_dB, ...
    num_candidatos, ...
    dist_min_candidatos_kHz);

