    'VariableNames', { ...
    'punto', ...
    'led', ...
    'metodo', ...
    'fc_detectada_kHz', ...
    'score_dB', ...
    'ON_prom_dB', ...
    'OFF_prom_dB', ...
    'rep_0dB', ...
    'rep_3dB', ...
    'rep_total', ...
    'criterio_dB', ...
    'umbral_repeticiones', ...
    'supera_3dB'});

tabla_candidatos = table();

for i = 1:numel(idx_candidatos)

    idx_i = idx_candidatos(i);

    if score_prom_dB(idx_i) >= criterio_dB && ...
            rep_3dB(idx_i) >= umbral_repeticiones

        supera_i = "Si";
    else
        supera_i = "No";
    end

    fila = table( ...
        nombre_punto, ...
        nombre_led, ...
        nombre_metodo, ...
        i, ...
        f_banda_kHz(idx_i), ...
        score_prom_dB(idx_i), ...
        PSD_ON_prom_dB(idx_i), ...
        PSD_OFF_prom_dB(idx_i), ...
        rep_0dB(idx_i), ...
        rep_3dB(idx_i), ...
        nRep, ...
        supera_i, ...
        'VariableNames', { ...
        'punto', ...
        'led', ...
        'metodo', ...
        'ranking', ...
        'fc_kHz', ...
        'score_dB', ...
        'ON_prom_dB', ...
        'OFF_prom_dB', ...
        'rep_0dB', ...
        'rep_3dB', ...
        'rep_total', ...
        'supera_3dB'});

    tabla_candidatos = [tabla_candidatos; fila];
end

tabla_score = table( ...
