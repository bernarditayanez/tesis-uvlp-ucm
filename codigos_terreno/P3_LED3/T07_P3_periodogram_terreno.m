function [t, y, Fs, N_original] = leer_csv_rigol_terreno(nombre_archivo, Fs_default)

    M = readmatrix(nombre_archivo);

    if size(M, 2) < 2
        error('El archivo no contiene al menos dos columnas:\n%s', nombre_archivo);
    end

    columnas_validas = [];

    for c = 1:size(M, 2)

        if sum(isfinite(M(:, c))) > 10
            columnas_validas = [columnas_validas c]; %#ok<AGROW>
        end
    end

    if numel(columnas_validas) < 2
        error('No se detectaron dos columnas numericas validas:\n%s', nombre_archivo);
    end

    t = M(:, columnas_validas(1));
    y = M(:, columnas_validas(2));

    idx_validos = isfinite(t) & isfinite(y);

    t = t(idx_validos);
    y = y(idx_validos);

    t = t(:);
    y = y(:);

    N_original = numel(y);

    if N_original < 10
        error('El archivo contiene muy pocas muestras validas:\n%s', nombre_archivo);
    end

    dt = diff(t);
    dt = dt(isfinite(dt) & dt > 0);

    if isempty(dt)
        Fs = Fs_default;
    else
        Fs = 1/median(dt);
    end

    if ~isfinite(Fs) || Fs <= 0
        Fs = Fs_default;
    end
end

function [idx_candidatos, fc_candidatos_kHz, score_candidatos_dB] = ...
        seleccionar_candidatos_globales(f_kHz, score_dB, num_candidatos, dist_min_kHz)

    f_kHz = f_kHz(:);
    score_dB = score_dB(:);

    idx_validos = isfinite(f_kHz) & isfinite(score_dB);

    f_kHz = f_kHz(idx_validos);
    score_dB = score_dB(idx_validos);

    idx_base = find(idx_validos);

    if numel(score_dB) < 3

        idx_candidatos = [];
        fc_candidatos_kHz = [];
        score_candidatos_dB = [];
        return;
    end

    idx_picos_locales = find( ...
        score_dB(2:end-1) >= score_dB(1:end-2) & ...
        score_dB(2:end-1) > score_dB(3:end)) + 1;

    if isempty(idx_picos_locales)
        idx_picos_locales = (1:numel(score_dB)).';
    end

    [~, orden] = sort(score_dB(idx_picos_locales), 'descend');

    idx_picos_ordenados = idx_picos_locales(orden);

    idx_seleccionados_local = [];

    for i = 1:numel(idx_picos_ordenados)

        idx_actual = idx_picos_ordenados(i);

        if isempty(idx_seleccionados_local)

            aceptar = true;

        else

            aceptar = all( ...
                abs(f_kHz(idx_actual) - f_kHz(idx_seleccionados_local)) >= dist_min_kHz);
        end

        if aceptar

            idx_seleccionados_local = [idx_seleccionados_local; idx_actual]; %#ok<AGROW>
        end

        if numel(idx_seleccionados_local) >= num_candidatos
            break;
        end
    end

    idx_candidatos = idx_base(idx_seleccionados_local);

    fc_candidatos_kHz = f_kHz(idx_seleccionados_local);
    score_candidatos_dB = score_dB(idx_seleccionados_local);
end

function guardar_figura(fig, carpeta_salida, nombre_archivo)

    archivo_png = fullfile(carpeta_salida, [nombre_archivo '.png']);
    archivo_fig = fullfile(carpeta_salida, [nombre_archivo '.fig']);

    try
        exportgraphics(fig, archivo_png, 'Resolution', 300);
    catch
        print(fig, archivo_png, '-dpng', '-r300');
    end

    savefig(fig, archivo_fig);
end

function guardar_tabla_como_figura(tabla, titulo_tabla, archivo_png, archivo_fig)

    if isempty(tabla)
        warning('La tabla esta vacia. No se guardara la figura.');
        return;
    end

    data_cell = formatear_tabla_para_figura(tabla);
    nombres_columnas = tabla.Properties.VariableNames;

    nFilas = height(tabla);
    nColumnas = width(tabla);

    ancho_columnas = zeros(1, nColumnas);

    for c = 1:nColumnas

        largo_maximo = length(nombres_columnas{c});

        for i = 1:nFilas
            largo_maximo = max(largo_maximo, length(data_cell{i, c}));
        end

        ancho_columnas(c) = max(75, min(160, 8*largo_maximo + 24));
    end

    margen_izquierdo = 30;
    margen_derecho = 30;
    margen_inferior = 25;

    alto_titulo = 55;
    alto_fila = 28;
    alto_encabezado = 30;

    ancho_tabla = sum(ancho_columnas);
    alto_tabla = alto_encabezado + nFilas*alto_fila;

    ancho_figura = margen_izquierdo + ancho_tabla + margen_derecho;
    alto_figura = margen_inferior + alto_tabla + alto_titulo + 15;

    fig = figure( ...
        'Color', 'w', ...
        'Units', 'pixels', ...
        'Position', [100 100 ancho_figura alto_figura]);

    ax = axes( ...
        'Parent', fig, ...
        'Units', 'pixels', ...
        'Position', [0 0 ancho_figura alto_figura]);

    axis(ax, [0 ancho_figura 0 alto_figura]);
    axis(ax, 'off');
    hold(ax, 'on');

    text( ...
        ax, ...
        ancho_figura/2, ...
        alto_figura - 28, ...
        titulo_tabla, ...
        'HorizontalAlignment', ...
        'center', ...
        'VerticalAlignment', ...
        'middle', ...
        'FontWeight', ...
        'bold', ...
        'FontSize', ...
        15, ...
        'Interpreter', ...
        'none');

    x0 = margen_izquierdo;
    y0 = margen_inferior + alto_tabla;

    color_encabezado = [0.93 0.93 0.93];
    color_fila_1 = [1 1 1];
    color_fila_2 = [0.94 0.94 0.94];
    color_borde = [0.65 0.65 0.65];

    x = x0;

    for c = 1:nColumnas

        rectangle( ...
            ax, ...
            'Position', [ ...
            x, ...
            y0 - alto_encabezado, ...
            ancho_columnas(c), ...
            alto_encabezado], ...
            'FaceColor', color_encabezado, ...
            'EdgeColor', color_borde, ...
            'LineWidth', 0.8);

        text( ...
            ax, ...
            x + ancho_columnas(c)/2, ...
            y0 - alto_encabezado/2, ...
            nombres_columnas{c}, ...
            'HorizontalAlignment', ...
            'center', ...
            'VerticalAlignment', ...
            'middle', ...
            'FontWeight', ...
            'bold', ...
            'FontSize', ...
            9, ...
            'Interpreter', ...
            'none');

        x = x + ancho_columnas(c);
    end

    for i = 1:nFilas

        y = y0 - alto_encabezado - i*alto_fila;

        if mod(i, 2) == 0
            color_fila = color_fila_2;
        else
            color_fila = color_fila_1;
        end

        x = x0;

        for c = 1:nColumnas

            rectangle( ...
                ax, ...
                'Position', [ ...
                x, ...
                y, ...
                ancho_columnas(c), ...
                alto_fila], ...
                'FaceColor', color_fila, ...
                'EdgeColor', [0.88 0.88 0.88], ...
                'LineWidth', 0.5);

            text( ...
                ax, ...
                x + ancho_columnas(c)/2, ...
                y + alto_fila/2, ...
                data_cell{i, c}, ...
                'HorizontalAlignment', ...
                'center', ...
                'VerticalAlignment', ...
                'middle', ...
                'FontSize', ...
                9, ...
                'Interpreter', ...
                'none');

            x = x + ancho_columnas(c);
        end
    end

    drawnow;

    print(fig, archivo_png, '-dpng', '-r300');
    savefig(fig, archivo_fig);
end

function data_cell = formatear_tabla_para_figura(tabla)

    nFilas = height(tabla);
    nColumnas = width(tabla);

    data_cell = cell(nFilas, nColumnas);

    nombres_columnas = tabla.Properties.VariableNames;

    for c = 1:nColumnas

        nombre = nombres_columnas{c};
        columna = tabla.(nombre);

        for i = 1:nFilas

            if iscell(columna)
                valor = columna{i};
            else
                valor = columna(i);
            end

            if isnumeric(valor)

                if isnan(valor)

                    texto = '';

                elseif contains(nombre, 'kHz', 'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains(nombre, 'Hz', 'IgnoreCase', true)

                    texto = sprintf('%.0f', valor);

                elseif contains(nombre, 'dB', 'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains(nombre, 'rep', 'IgnoreCase', true)

                    texto = sprintf('%.0f', valor);

                else

                    texto = sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor
                    texto = 'Si';
                else
                    texto = 'No';
                end

            elseif isstring(valor)

                if strlength(valor) == 0
                    texto = '';
                else
                    texto = char(valor);
                end

            elseif ischar(valor)

                texto = valor;

            else

                texto = char(string(valor));
            end

            data_cell{i, c} = texto;
        end
    end
end

function [x_out, y1_out, y2_out] = reducir_puntos_grafico(x, y1, y2, nmax)

    x = x(:);
    y1 = y1(:);
    y2 = y2(:);

    n = numel(x);

    if n > nmax
        idx = round(linspace(1, n, nmax));
    else
        idx = 1:n;
    end

    x_out = x(idx);
    y1_out = y1(idx);
    y2_out = y2(idx);
end