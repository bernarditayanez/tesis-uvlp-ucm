function [t, y] = leer_csv_rigol_terreno(nombre_archivo, Fs_configurada_Hz)

    M = readmatrix(nombre_archivo);

    if size(M, 2) < 2

        error( ...
            'El archivo no contiene al menos dos columnas:\n%s', ...
            nombre_archivo);
    end

    columnas_validas = [];

    for c = 1:size(M, 2)

        if sum(isfinite(M(:, c))) > 10
            columnas_validas = [columnas_validas c]; %#ok<AGROW>
        end
    end

    if numel(columnas_validas) < 1

        error( ...
            'No se detectaron columnas numericas validas:\n%s', ...
            nombre_archivo);
    end

    M = M(:, columnas_validas);

    t = [];
    y = [];

    if size(M, 2) >= 2

        for c = 1:(size(M, 2) - 1)

            t_cand = M(:, c);
            y_cand = M(:, c + 1);

            idx_validos = isfinite(t_cand) & isfinite(y_cand);

            t_temp = t_cand(idx_validos);
            y_temp = y_cand(idx_validos);

            if numel(y_temp) < 10
                continue;
            end

            t_temp = t_temp(:);
            y_temp = y_temp(:);

            duracion_temp = t_temp(end) - t_temp(1);

            if duracion_temp <= 0 || ~isfinite(duracion_temp)
                continue;
            end

            Fs_temp = (numel(t_temp) - 1) / duracion_temp;

            error_Fs_pct = abs(Fs_temp - Fs_configurada_Hz) / Fs_configurada_Hz * 100;

            if error_Fs_pct <= 10 && std(y_temp, 'omitnan') > 0

                t = t_temp;
                y = y_temp;
                return;
            end
        end
    end

    if isempty(y)

        y = M(:, end);
        y = y(isfinite(y));
        y = y(:);

        if numel(y) < 10

            error( ...
                'El archivo contiene muy pocas muestras validas:\n%s', ...
                nombre_archivo);
        end

        t = (0:numel(y)-1)'/Fs_configurada_Hz;
    end
end

