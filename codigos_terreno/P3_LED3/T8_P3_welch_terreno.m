function datos_celdas = formatear_tabla_para_figura(tabla)

    nFilas = height(tabla);
    nColumnas = width(tabla);

    datos_celdas = cell(nFilas, nColumnas);

    nombres_columnas = tabla.Properties.VariableNames;

    for c = 1:nColumnas

        nombre_columna = nombres_columnas{c};
        columna = tabla.(nombre_columna);

        for i = 1:nFilas

            if iscell(columna)
                valor = columna{i};
            else
                valor = columna(i);
            end

            if isnumeric(valor)

                if isnan(valor)

                    texto = '';

                elseif contains( ...
                        nombre_columna, ...
                        'kHz', ...
                        'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains( ...
                        nombre_columna, ...
                        'Hz', ...
                        'IgnoreCase', true)

                    texto = sprintf('%.0f', valor);

                elseif contains( ...
                        nombre_columna, ...
                        'dB', ...
                        'IgnoreCase', true)

                    texto = sprintf('%.4f', valor);

                elseif contains( ...
                        nombre_columna, ...
                        'rep', ...
                        'IgnoreCase', true)

                    texto = sprintf('%.0f', valor);

                else

                    texto = sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor
                    texto = 'Si';
                else
                    texto = 'No';
                end

            elseif isstring(valor)

                texto = char(valor);

            elseif ischar(valor)

                texto = valor;

            else

                texto = char(string(valor));
            end

            datos_celdas{i, c} = texto;
        end
    end
end

function [x_salida, y1_salida, y2_salida] = ...
    reducir_puntos_grafico(x, y1, y2, nMaximo)

    x = x(:);
    y1 = y1(:);
    y2 = y2(:);

    nPuntos = numel(x);

    if nPuntos > nMaximo

        indices = round( ...
            linspace(1, nPuntos, nMaximo));

    else

        indices = 1:nPuntos;
    end

    x_salida = x(indices);
    y1_salida = y1(indices);
    y2_salida = y2(indices);
end