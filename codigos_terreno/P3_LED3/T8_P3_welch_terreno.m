%% T08_P3_welch_terreno.m
% Analisis Welch - P3 / LED terreno 3
%
% Antes de ejecutar este script, modificar las variables carpeta_ON
% y carpeta_OFF con las rutas locales donde se encuentran los archivos .csv
% de la medicion correspondiente.
%
% La carpeta_ON debe contener los archivos ON_P3_REP*.csv indicados
% en la lista archivos_ON.
% La carpeta_OFF debe contener los archivos OFF comunes indicados
% en la lista archivos_OFF.
%
% Ejemplo:
% carpeta_ON  = 'C:\Users\NombreUsuario\Desktop\Terreno_ON_M3';
% carpeta_OFF = 'C:\Users\NombreUsuario\Desktop\Terreno_OFF';

clear;
clc;
close all;

%% 1. Configuracion

carpeta_base = 'C:\Users\berni\OneDrive\Escritorio\Modulo Prof\Archivos Tesis\Toma de Datos\Pruebas en terreno';

carpeta_ON = fullfile(carpeta_base, 'Terreno_ON_M3');
carpeta_OFF = fullfile(carpeta_base, 'Terreno_OFF');

carpeta_salida = fullfile( ...
    carpeta_base, ...
    'Resultados_Terreno', ...
    'P3_LED3', ...
    '02_Welch');

if ~exist(carpeta_salida, 'dir')
    mkdir(carpeta_salida);
end

nombre_punto = "P3";
nombre_led = "LED terreno 3";
nombre_metodo = "Welch";

nRep = 3;

archivos_ON = cell(nRep, 1);
archivos_OFF = cell(nRep, 1);

for r = 1:nRep

    archivos_ON{r} = fullfile( ...
        carpeta_ON, ...
        sprintf('ON_P3_REP%d.csv', r));

    archivos_OFF{r} = fullfile( ...
        carpeta_OFF, ...
        sprintf('OFF_REP%d.csv', r));
end

% Banda de analisis
fmin_Hz = 30e3;
fmax_Hz = 90e3;

% Frecuencia detectada previamente mediante Periodograma P3
f_ref_periodograma_Hz = 57.6580e3;

% Confirmacion local alrededor de la frecuencia del Periodograma
usar_confirmacion_local = true;
ventana_confirmacion_Hz = 350;

% Criterios de deteccion
criterio_dB = 3;
umbral_repeticiones = nRep;

% Busqueda de candidatos
num_candidatos = 7;
distancia_minima_Hz = 50;
ventana_local_Hz = 200;

% Frecuencia de muestreo configurada en el osciloscopio
Fs_configurada_Hz = 50e6;

% Parametros Welch
Nseg_objetivo = 2^20;
fraccion_solapamiento = 0.50;

% Rango amplio para graficas
fmax_amplio_Hz = 5e6;

fprintf('\n============================================================\n');
fprintf('PUNTO 3 / LED TERRENO 3 - WELCH CORREGIDO\n');
fprintf('============================================================\n');
fprintf('Carpeta base:\n%s\n\n', carpeta_base);
fprintf('Carpeta ON:\n%s\n\n', carpeta_ON);
fprintf('Carpeta OFF:\n%s\n\n', carpeta_OFF);
fprintf('Carpeta salida:\n%s\n\n', carpeta_salida);
fprintf('Fs configurada: %.6f MSa/s\n', Fs_configurada_Hz/1e6);
fprintf('Nseg objetivo: %d muestras\n', Nseg_objetivo);
fprintf('Solapamiento: %.1f %%\n', fraccion_solapamiento*100);
fprintf('Referencia Periodograma P3: %.4f kHz\n', f_ref_periodograma_Hz/1e3);
fprintf('Ventana confirmacion local: +/- %.3f kHz\n', ventana_confirmacion_Hz/1e3);

%% 2. Verificacion de archivos

for r = 1:nRep

    if ~exist(archivos_ON{r}, 'file')

        error( ...
            'No existe el archivo ON de la repeticion %d:\n%s', ...
            r, ...
            archivos_ON{r});
    end

    if ~exist(archivos_OFF{r}, 'file')

        error( ...
            'No existe el archivo OFF de la repeticion %d:\n%s', ...
            r, ...
            archivos_OFF{r});
    end
end

fprintf('\nArchivos verificados correctamente.\n');

%% 3. Lectura y calculo Welch por repeticion

f_ref_Hz = [];

PSD_ON_mat_dB = [];
PSD_OFF_mat_dB = [];

info_reps = table();

for r = 1:nRep

    fprintf('\n------------------------------------------------------------\n');
    fprintf('Repeticion %d/%d\n', r, nRep);
    fprintf('ON : %s\n', archivos_ON{r});
    fprintf('OFF: %s\n', archivos_OFF{r});

    [tON, xON] = leer_csv_rigol_terreno(archivos_ON{r}, Fs_configurada_Hz);
    [tOFF, xOFF] = leer_csv_rigol_terreno(archivos_OFF{r}, Fs_configurada_Hz);

    N_ON_original = numel(xON);
    N_OFF_original = numel(xOFF);

    N_usado = min(N_ON_original, N_OFF_original);

    if N_usado < Nseg_objetivo

        error( ...
            ['La repeticion %d contiene menos muestras que el segmento ', ...
             'Welch configurado. Muestras disponibles: %d.'], ...
            r, ...
            N_usado);
    end

    tON = tON(1:N_usado);
    xON = xON(1:N_usado);

    tOFF = tOFF(1:N_usado);
    xOFF = xOFF(1:N_usado);

    duracion_ON_s = tON(end) - tON(1);
    duracion_OFF_s = tOFF(end) - tOFF(1);

    if duracion_ON_s <= 0 || duracion_OFF_s <= 0

        warning( ...
            ['No se detecto una duracion valida desde la columna de tiempo ', ...
             'en la repeticion %d. Se reconstruye el tiempo con Fs configurada.'], ...
            r);

        tON = (0:N_usado-1)'/Fs_configurada_Hz;
        tOFF = (0:N_usado-1)'/Fs_configurada_Hz;

        duracion_ON_s = tON(end) - tON(1);
        duracion_OFF_s = tOFF(end) - tOFF(1);
    end

    Fs_ON_duracion_Hz = (N_usado - 1) / duracion_ON_s;
    Fs_OFF_duracion_Hz = (N_usado - 1) / duracion_OFF_s;

    error_Fs_ON_pct = ...
        abs(Fs_ON_duracion_Hz - Fs_configurada_Hz) / ...
        Fs_configurada_Hz * 100;

    error_Fs_OFF_pct = ...
        abs(Fs_OFF_duracion_Hz - Fs_configurada_Hz) / ...
        Fs_configurada_Hz * 100;

    if error_Fs_ON_pct > 5

        warning( ...
            ['La Fs estimada por duracion para ON difiere mas de 5 %% ', ...
             'respecto de 50 MSa/s en la repeticion %d. ', ...
             'Se utilizara Fs configurada.'], ...
            r);
    end

    if error_Fs_OFF_pct > 5

        warning( ...
            ['La Fs estimada por duracion para OFF difiere mas de 5 %% ', ...
             'respecto de 50 MSa/s en la repeticion %d. ', ...
             'Se utilizara Fs configurada.'], ...
            r);
    end

    Fs_usada_Hz = Fs_configurada_Hz;

    xON = xON - mean(xON, 'omitnan');
    xOFF = xOFF - mean(xOFF, 'omitnan');

    xON(~isfinite(xON)) = 0;
    xOFF(~isfinite(xOFF)) = 0;

    Nseg = min(Nseg_objetivo, N_usado);

    noverlap = floor(fraccion_solapamiento*Nseg);

    if noverlap >= Nseg
        noverlap = Nseg - 1;
    end

    nfft = Nseg;

    ventana_welch = hann(Nseg, 'periodic');

    salto_segmento = Nseg - noverlap;

    num_segmentos = ...
        1 + floor((N_usado - Nseg)/salto_segmento);

    df_Hz = Fs_usada_Hz/nfft;

    fprintf('N ON original       = %d muestras\n', N_ON_original);
    fprintf('N OFF original      = %d muestras\n', N_OFF_original);
    fprintf('N usado             = %d muestras\n', N_usado);
    fprintf('Duracion ON         = %.9f s\n', duracion_ON_s);
    fprintf('Duracion OFF        = %.9f s\n', duracion_OFF_s);
    fprintf('Fs ON por duracion  = %.6f MSa/s\n', Fs_ON_duracion_Hz/1e6);
    fprintf('Fs OFF por duracion = %.6f MSa/s\n', Fs_OFF_duracion_Hz/1e6);
    fprintf('Fs usada            = %.6f MSa/s\n', Fs_usada_Hz/1e6);
    fprintf('Nseg                = %d muestras\n', Nseg);
    fprintf('noverlap            = %d muestras\n', noverlap);
    fprintf('Solapamiento        = %.2f %%\n', 100*noverlap/Nseg);
    fprintf('Numero de segmentos = %d\n', num_segmentos);
    fprintf('nfft                = %d\n', nfft);
    fprintf('df aproximada       = %.6f Hz\n', df_Hz);

    [Pxx_ON, fON_Hz] = pwelch( ...
        xON, ...
        ventana_welch, ...
        noverlap, ...
        nfft, ...
        Fs_usada_Hz, ...
        'onesided');

    [Pxx_OFF, fOFF_Hz] = pwelch( ...
        xOFF, ...
        ventana_welch, ...
        noverlap, ...
        nfft, ...
        Fs_usada_Hz, ...
        'onesided');

    fON_Hz = fON_Hz(:);
    fOFF_Hz = fOFF_Hz(:);

    PSD_ON_dB = 10*log10(Pxx_ON(:) + eps);
    PSD_OFF_dB = 10*log10(Pxx_OFF(:) + eps);

    if numel(fON_Hz) ~= numel(fOFF_Hz) || ...
            max(abs(fON_Hz - fOFF_Hz)) > 1e-9

        error( ...
            'Las grillas de frecuencia ON y OFF no coinciden en la repeticion %d.', ...
            r);
    end

    if max(fON_Hz) < fmax_Hz

        error( ...
            'La grilla Welch no cubre la banda de 30 a 90 kHz.');
    end

    if isempty(f_ref_Hz)

        f_ref_Hz = fON_Hz;

        PSD_ON_mat_dB = nan(numel(f_ref_Hz), nRep);
        PSD_OFF_mat_dB = nan(numel(f_ref_Hz), nRep);
    end

    PSD_ON_mat_dB(:, r) = interp1( ...
        fON_Hz, ...
        PSD_ON_dB, ...
        f_ref_Hz, ...
        'linear', ...
        NaN);

    PSD_OFF_mat_dB(:, r) = interp1( ...
        fOFF_Hz, ...
        PSD_OFF_dB, ...
        f_ref_Hz, ...
        'linear', ...
        NaN);

    info_reps = [info_reps; crear_fila_info( ...
        string(archivos_ON{r}), ...
        "ON", ...
        r, ...
        N_ON_original, ...
        N_usado, ...
        duracion_ON_s, ...
        Fs_ON_duracion_Hz, ...
        Fs_usada_Hz, ...
        error_Fs_ON_pct, ...
        Nseg, ...
        noverlap, ...
        num_segmentos, ...
        nfft, ...
        df_Hz)];

    info_reps = [info_reps; crear_fila_info( ...
        string(archivos_OFF{r}), ...
        "OFF", ...
        r, ...
        N_OFF_original, ...
        N_usado, ...
        duracion_OFF_s, ...
        Fs_OFF_duracion_Hz, ...
        Fs_usada_Hz, ...
        error_Fs_OFF_pct, ...
        Nseg, ...
        noverlap, ...
        num_segmentos, ...
        nfft, ...
        df_Hz)];

    clear tON tOFF xON xOFF
    clear Pxx_ON Pxx_OFF PSD_ON_dB PSD_OFF_dB
end

%% 4. Promedios y score ON-OFF

PSD_ON_prom_dB = mean(PSD_ON_mat_dB, 2, 'omitnan');
PSD_OFF_prom_dB = mean(PSD_OFF_mat_dB, 2, 'omitnan');

score_rep_dB = PSD_ON_mat_dB - PSD_OFF_prom_dB;
score_prom_dB = mean(score_rep_dB, 2, 'omitnan');

f_ref_Hz = f_ref_Hz(:);
PSD_ON_prom_dB = PSD_ON_prom_dB(:);
PSD_OFF_prom_dB = PSD_OFF_prom_dB(:);
score_prom_dB = score_prom_dB(:);

%% 5. Preparar banda de analisis

idx_banda = ...
    f_ref_Hz >= fmin_Hz & ...
    f_ref_Hz <= fmax_Hz;

if ~any(idx_banda)

    error( ...
        'No existen puntos dentro de la banda de 30 a 90 kHz.');
end

f_banda_Hz = f_ref_Hz(idx_banda);

PSD_ON_banda_dB = PSD_ON_prom_dB(idx_banda);
PSD_OFF_banda_dB = PSD_OFF_prom_dB(idx_banda);
score_banda_dB = score_prom_dB(idx_banda);

PSD_ON_banda_reps_dB = PSD_ON_mat_dB(idx_banda, :);
PSD_OFF_banda_reps_dB = PSD_OFF_mat_dB(idx_banda, :);
score_banda_reps_dB = score_rep_dB(idx_banda, :);

idx_validos = ...
    isfinite(f_banda_Hz) & ...
    isfinite(PSD_ON_banda_dB) & ...
    isfinite(PSD_OFF_banda_dB) & ...
    isfinite(score_banda_dB);

f_banda_Hz = f_banda_Hz(idx_validos);

PSD_ON_banda_dB = PSD_ON_banda_dB(idx_validos);
PSD_OFF_banda_dB = PSD_OFF_banda_dB(idx_validos);
score_banda_dB = score_banda_dB(idx_validos);

PSD_ON_banda_reps_dB = ...
    PSD_ON_banda_reps_dB(idx_validos, :);

PSD_OFF_banda_reps_dB = ...
    PSD_OFF_banda_reps_dB(idx_validos, :);

score_banda_reps_dB = ...
    score_banda_reps_dB(idx_validos, :);

f_banda_kHz = f_banda_Hz/1e3;

%% 6. Busqueda de candidatos

if usar_confirmacion_local

    idx_busqueda = ...
        f_banda_Hz >= f_ref_periodograma_Hz - ventana_confirmacion_Hz & ...
        f_banda_Hz <= f_ref_periodograma_Hz + ventana_confirmacion_Hz;

    if ~any(idx_busqueda)

        error( ...
            'No hay datos dentro de la ventana local alrededor de %.4f kHz.', ...
            f_ref_periodograma_Hz/1e3);
    end

else

    idx_busqueda = true(size(f_banda_Hz));
end

f_busqueda_Hz = f_banda_Hz(idx_busqueda);
score_busqueda_dB = score_banda_dB(idx_busqueda);

[score_max_busqueda_dB, idx_max_busqueda] = max(score_busqueda_dB);
f_max_busqueda_Hz = f_busqueda_Hz(idx_max_busqueda);

fprintf('\n============================================================\n');
fprintf('MAXIMO WELCH EN ZONA DE BUSQUEDA\n');
fprintf('============================================================\n');
fprintf('Frecuencia = %.3f Hz = %.4f kHz\n', ...
    f_max_busqueda_Hz, ...
    f_max_busqueda_Hz/1e3);
fprintf('Score      = %.4f dB\n', score_max_busqueda_dB);

[picos_dB, frecuencias_picos_Hz] = findpeaks( ...
    score_busqueda_dB, ...
    f_busqueda_Hz, ...
    'MinPeakDistance', ...
    distancia_minima_Hz);

idx_positivos = picos_dB > 0;

picos_dB = picos_dB(idx_positivos);

frecuencias_picos_Hz = ...
    frecuencias_picos_Hz(idx_positivos);

if isempty(picos_dB)

    warning( ...
        'No se encontraron picos positivos. Se utilizara el maximo de la zona de busqueda.');

    picos_dB = score_max_busqueda_dB;
    frecuencias_picos_Hz = f_max_busqueda_Hz;
end

[picos_dB, idx_orden] = sort(picos_dB, 'descend');

frecuencias_picos_Hz = ...
    frecuencias_picos_Hz(idx_orden);

num_candidatos_usados = ...
    min(num_candidatos, numel(picos_dB));

score_peak_dB = ...
    picos_dB(1:num_candidatos_usados);

fc_candidatas_Hz = ...
    frecuencias_picos_Hz(1:num_candidatos_usados);

nCandidatos = numel(fc_candidatas_Hz);

%% 7. Analisis local y repetibilidad

score_local_dB = nan(nCandidatos, 1);
f_local_Hz = nan(nCandidatos, 1);

ON_dB = nan(nCandidatos, 1);
OFF_dB = nan(nCandidatos, 1);

rep_positivas = zeros(nCandidatos, 1);
rep_3dB = zeros(nCandidatos, 1);

for i = 1:nCandidatos

    fc_Hz = fc_candidatas_Hz(i);

    idx_local = ...
        f_ref_Hz >= fc_Hz - ventana_local_Hz & ...
        f_ref_Hz <= fc_Hz + ventana_local_Hz;

    f_local_temp_Hz = f_ref_Hz(idx_local);
    score_local_temp_dB = score_prom_dB(idx_local);

    if isempty(score_local_temp_dB)
        continue;
    end

    [score_local_dB(i), idx_max_local] = ...
        max(score_local_temp_dB);

    f_local_Hz(i) = ...
        f_local_temp_Hz(idx_max_local);

    ON_dB(i) = interp1( ...
        f_ref_Hz, ...
        PSD_ON_prom_dB, ...
        f_local_Hz(i), ...
        'linear', ...
        NaN);

    OFF_dB(i) = interp1( ...
        f_ref_Hz, ...
        PSD_OFF_prom_dB, ...
        f_local_Hz(i), ...
        'linear', ...
        NaN);

    for r = 1:nRep

        score_rep_local_dB = interp1( ...
            f_ref_Hz, ...
            score_rep_dB(:, r), ...
            f_local_Hz(i), ...
            'linear', ...
            NaN);

        if isfinite(score_rep_local_dB)

            if score_rep_local_dB > 0
                rep_positivas(i) = rep_positivas(i) + 1;
            end

            if score_rep_local_dB >= criterio_dB
                rep_3dB(i) = rep_3dB(i) + 1;
            end
        end
    end
end

supera_3dB = score_local_dB >= criterio_dB & rep_3dB >= umbral_repeticiones;

tabla_candidatos = table( ...
    fc_candidatas_Hz, ...
    fc_candidatas_Hz/1e3, ...
    score_peak_dB, ...
    f_local_Hz, ...
    f_local_Hz/1e3, ...
    score_local_dB, ...
    ON_dB, ...
    OFF_dB, ...
    rep_positivas, ...
    rep_3dB, ...
    repmat(nRep, nCandidatos, 1), ...
    supera_3dB, ...
    'VariableNames', { ...
    'fc_Hz', ...
    'fc_kHz', ...
    'score_peak_dB', ...
    'f_local_Hz', ...
    'f_local_kHz', ...
    'score_local_dB', ...
    'ON_dB', ...
    'OFF_dB', ...
    'rep_positivas', ...
    'rep_3dB', ...
    'rep_totales', ...
    'supera_3dB'});

tabla_candidatos = sortrows( ...
    tabla_candidatos, ...
    'score_local_dB', ...
    'descend');

%% 8. Seleccion de frecuencia principal

idx_validos_principal = ...
    tabla_candidatos.score_local_dB >= criterio_dB & ...
    tabla_candidatos.rep_positivas == tabla_candidatos.rep_totales & ...
    tabla_candidatos.rep_3dB >= umbral_repeticiones;

if any(idx_validos_principal)

    tabla_validos = ...
        tabla_candidatos(idx_validos_principal, :);

    [~, idx_mejor] = ...
        max(tabla_validos.score_local_dB);

    fc_principal_Hz = ...
        tabla_validos.f_local_Hz(idx_mejor);

    score_principal_dB = ...
        tabla_validos.score_local_dB(idx_mejor);

    ON_principal_dB = ...
        tabla_validos.ON_dB(idx_mejor);

    OFF_principal_dB = ...
        tabla_validos.OFF_dB(idx_mejor);

    rep_positivas_principal = ...
        tabla_validos.rep_positivas(idx_mejor);

    rep_3dB_principal = ...
        tabla_validos.rep_3dB(idx_mejor);

else

    warning( ...
        ['No se encontraron candidatos con score >= %.1f dB y ', ...
         'repetibilidad completa. Se utilizara el mayor score dentro de la zona de busqueda.'], ...
        criterio_dB);

    fc_principal_Hz = ...
        tabla_candidatos.f_local_Hz(1);

    score_principal_dB = ...
        tabla_candidatos.score_local_dB(1);

    ON_principal_dB = ...
        tabla_candidatos.ON_dB(1);

    OFF_principal_dB = ...
        tabla_candidatos.OFF_dB(1);

    rep_positivas_principal = ...
        tabla_candidatos.rep_positivas(1);

    rep_3dB_principal = ...
        tabla_candidatos.rep_3dB(1);
end

fc_principal_kHz = fc_principal_Hz/1e3;

if score_principal_dB >= criterio_dB && ...
        rep_positivas_principal >= umbral_repeticiones && ...
        rep_3dB_principal >= umbral_repeticiones

    supera_criterio = "Si";

else

    supera_criterio = "No";
end

fprintf('\n============================================================\n');
fprintf('RESULTADO WELCH CORREGIDO\n');
fprintf('============================================================\n');
fprintf('Frecuencia principal = %.3f Hz = %.4f kHz\n', ...
    fc_principal_Hz, ...
    fc_principal_kHz);
fprintf('Score principal      = %.4f dB\n', ...
    score_principal_dB);
fprintf('Repeticiones > 0 dB  = %d/%d\n', ...
    rep_positivas_principal, ...
    nRep);
fprintf('Repeticiones >= 3 dB = %d/%d\n', ...
    rep_3dB_principal, ...
    nRep);

tabla_resultado = table( ...
    nombre_punto, ...
    nombre_led, ...
    nombre_metodo, ...
    f_ref_periodograma_Hz/1e3, ...
    ventana_confirmacion_Hz/1e3, ...
    fc_principal_kHz, ...
    score_principal_dB, ...
    ON_principal_dB, ...
    OFF_principal_dB, ...
    rep_positivas_principal, ...
    rep_3dB_principal, ...
    nRep, ...
    criterio_dB, ...
    supera_criterio, ...
    'VariableNames', { ...
    'punto', ...
    'led', ...
    'metodo', ...
    'f_ref_kHz', ...
    'ventana_kHz', ...
    'fc_detectada_kHz', ...
    'score_dB', ...
    'ON_prom_dB', ...
    'OFF_prom_dB', ...
    'rep_positivas', ...
    'rep_3dB', ...
    'rep_totales', ...
    'criterio_dB', ...
    'supera_3dB'});

tabla_score = table( ...
    f_banda_kHz(:), ...
    PSD_ON_banda_dB(:), ...
    PSD_OFF_banda_dB(:), ...
    score_banda_dB(:), ...
    'VariableNames', { ...
    'f_kHz', ...
    'PSD_ON_prom_dB', ...
    'PSD_OFF_prom_dB', ...
    'score_prom_dB'});

disp(tabla_resultado);
disp(tabla_candidatos);

%% 9. Guardar resultados

writetable( ...
    tabla_resultado, ...
    fullfile( ...
        carpeta_salida, ...
        'tabla_resultado_P3_welch.csv'));

writetable( ...
    tabla_candidatos, ...
    fullfile( ...
        carpeta_salida, ...
        'tabla_candidatos_P3_welch.csv'));

writetable( ...
    tabla_score, ...
    fullfile( ...
        carpeta_salida, ...
        'score_promedio_P3_welch.csv'));

writetable( ...
    info_reps, ...
    fullfile( ...
        carpeta_salida, ...
        'info_repeticiones_P3_welch.csv'));

%% 10. Tabla de candidatos como figura

tabla_figura = tabla_candidatos;

tabla_figura.fc_Hz = [];
tabla_figura.f_local_Hz = [];

tabla_figura.Properties.VariableNames = { ...
    'fc_kHz', ...
    'score_peak', ...
    'f_local_kHz', ...
    'score_local', ...
    'ON_dB', ...
    'OFF_dB', ...
    'rep_positivas', ...
    'rep_3dB', ...
    'rep_totales', ...
    'supera_3dB'};

