% y modificarla si los archivos .csv se encuentran en otra ruta local.
% La carpeta indicada debe contener los archivos ON_LED2_rep*.csv
% y OFF_LED2_rep*.csv definidos en las listas archivos_ON
% y archivos_OFF.
%
% Ejemplo:
% carpeta_csv = 'C:\Users\NombreUsuario\Desktop\Pruebas LED 2';

clear; 
clc; 
close all;

%% 1. Configuracion general

carpeta_csv = 'C:\Users\mudrood\Desktop\Modulo Prof\Archivos Tesis\Toma de Datos\Pruebas LED 2';

carpeta_general = fullfile(carpeta_csv, 'Resultados_LED2_modificados');
carpeta_salida = fullfile(carpeta_general, '03_Multitaper');

if ~exist(carpeta_general, 'dir')
    mkdir(carpeta_general);
end

if ~exist(carpeta_salida, 'dir')
    mkdir(carpeta_salida);
end

archivos_ON = {
    'ON_LED2_rep1.csv'
    'ON_LED2_rep2.csv'
    'ON_LED2_rep3.csv'
    'ON_LED2_rep4.csv'
};

archivos_OFF = {
    'OFF_LED2_rep1.csv'
    'OFF_LED2_rep2.csv'
    'OFF_LED2_rep3.csv'
    'OFF_LED2_rep4.csv'
};

nrep = numel(archivos_ON);

%% 2. Parametros Multitaper local

fc_ref_Hz = 45375;

ancho_local_Hz = 1000;

fmin_local = fc_ref_Hz - ancho_local_Hz;
fmax_local = fc_ref_Hz + ancho_local_Hz;

NW = 2.5;

umbralScoreRep_dB = 3;
ventana_rep_Hz = 200;

fprintf('\n============================================\n');
fprintf('MULTITAPER LOCAL LED 2\n');
fprintf('============================================\n');
fprintf('Carpeta entrada:\n%s\n', carpeta_csv);
fprintf('\nCarpeta salida:\n%s\n', carpeta_salida);
fprintf('\nFrecuencia referencia = %.3f Hz = %.3f kHz\n', fc_ref_Hz, fc_ref_Hz/1e3);
fprintf('Ventana local = %.1f Hz a %.1f Hz\n', fmin_local, fmax_local);
fprintf('NW = %.2f\n', NW);

%% 3. Lectura y calculo Multitaper por repeticion

P_ON = [];
P_OFF = [];
score_por_rep = [];
fc_por_rep = zeros(nrep,1);
score_local_max = zeros(nrep,1);
score_positivo_0dB = false(nrep,1);
score_positivo_3dB = false(nrep,1);

info_archivos = table();

for k = 1:nrep

    archivo_on = fullfile(carpeta_csv, archivos_ON{k});
    archivo_off = fullfile(carpeta_csv, archivos_OFF{k});

    [t_on, y_on] = leer_csv_rigol_simple_local(archivo_on);
    [t_off, y_off] = leer_csv_rigol_simple_local(archivo_off);

    Fs = 1 / median(diff(t_on));

    Fs_mean_on = 1 / mean(diff(t_on));
    Fs_median_on = 1 / median(diff(t_on));
    Fs_mean_off = 1 / mean(diff(t_off));
    Fs_median_off = 1 / median(diff(t_off));

    N_on = numel(y_on);
    N_off = numel(y_off);

    N = N_on;

    T_on = t_on(end) - t_on(1);
    T_off = t_off(end) - t_off(1);

    fprintf('\n--------------------------------------------\n');
    fprintf('Repeticion %d/%d\n', k, nrep);
    fprintf('ON : %s\n', archivos_ON{k});
    fprintf('OFF: %s\n', archivos_OFF{k});
    fprintf('N ON  = %d muestras\n', N_on);
    fprintf('N OFF = %d muestras\n', N_off);
    fprintf('Fs usada = %.6f MSa/s\n', Fs/1e6);
    fprintf('Duracion ON  = %.9f s\n', T_on);
    fprintf('Duracion OFF = %.9f s\n', T_off);

    info_archivos = [info_archivos; crear_fila_info( ...
        string(archivos_ON{k}), "ON", k, N_on, Fs_mean_on, Fs_median_on, T_on)];

    info_archivos = [info_archivos; crear_fila_info( ...
        string(archivos_OFF{k}), "OFF", k, N_off, Fs_mean_off, Fs_median_off, T_off)];

    if N_on ~= N_off
        warning('La repeticion %d tiene distinto numero de muestras ON/OFF.', k);
    end

    NFFT = N;

    [Pxx_on, f] = pmtm(y_on, NW, NFFT, Fs);
    [Pxx_off, f_off] = pmtm(y_off, NW, NFFT, Fs);

    if numel(f) ~= numel(f_off) || max(abs(f - f_off)) > 1e-9
        error('La grilla de frecuencia ON/OFF no coincide en la repeticion %d.', k);
    end

    P_ON(:,k) = 10*log10(Pxx_on + eps);
    P_OFF(:,k) = 10*log10(Pxx_off + eps);

    score_por_rep(:,k) = P_ON(:,k) - P_OFF(:,k);

    idx_local = f >= fmin_local & f <= fmax_local;

    if ~any(idx_local)
        error('La mascara local quedo vacia. Revisar fc_ref_Hz, ancho_local_Hz, Fs o NFFT.');
    end

    f_local = f(idx_local);
    score_local_rep = score_por_rep(idx_local,k);

    [score_local_max(k), idx_max] = max(score_local_rep);
    fc_por_rep(k) = f_local(idx_max);

    score_positivo_0dB(k) = score_local_max(k) > 0;
    score_positivo_3dB(k) = score_local_max(k) >= umbralScoreRep_dB;

    fprintf('fc local rep %d = %.3f Hz = %.3f kHz | score = %.4f dB\n', ...
        k, fc_por_rep(k), fc_por_rep(k)/1e3, score_local_max(k));
end

%% 4. Promedios generales

P_ON_prom = mean(P_ON, 2);
P_OFF_prom = mean(P_OFF, 2);

score_prom = P_ON_prom - P_OFF_prom;

idx_local = f >= fmin_local & f <= fmax_local;

f_local = f(idx_local);
P_ON_local = P_ON_prom(idx_local);
P_OFF_local = P_OFF_prom(idx_local);
score_local = score_prom(idx_local);

[score_local_prom_max, idx_max_prom] = max(score_local);

fc_local = f_local(idx_max_prom);

ON_dB = P_ON_local(idx_max_prom);
OFF_dB = P_OFF_local(idx_max_prom);

rep_positivas_0dB = sum(score_positivo_0dB);
rep_positivas_3dB = sum(score_positivo_3dB);

fprintf('\n============================================\n');
fprintf('RESULTADO MULTITAPER LOCAL LED 2\n');
fprintf('============================================\n');
fprintf('fc referencia = %.3f Hz = %.3f kHz\n', fc_ref_Hz, fc_ref_Hz/1e3);
fprintf('fc local promedio = %.3f Hz = %.3f kHz\n', fc_local, fc_local/1e3);
fprintf('score local promedio = %.4f dB\n', score_local_prom_max);
fprintf('ON  = %.4f dB/Hz\n', ON_dB);
fprintf('OFF = %.4f dB/Hz\n', OFF_dB);
fprintf('Repeticiones positivas > 0 dB: %d/%d\n', rep_positivas_0dB, nrep);
fprintf('Repeticiones positivas >= %.1f dB: %d/%d\n', ...
    umbralScoreRep_dB, rep_positivas_3dB, nrep);

