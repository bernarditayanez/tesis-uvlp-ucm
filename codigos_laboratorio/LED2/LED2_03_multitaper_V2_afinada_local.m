% Funcion local para guardar tablas como figura compacta

function guardar_tabla_como_figura_compacta(T, titulo_figura, archivo_png, archivo_fig)

    if isempty(T)
        warning('La tabla esta vacia. No se generara figura: %s', titulo_figura);
        return;
    end

    T_cell = table2cell(T);
    nombres = T.Properties.VariableNames;

    datos_txt = cell(size(T_cell));

    for i = 1:size(T_cell,1)
        for j = 1:size(T_cell,2)

            valor = T_cell{i,j};
            nombre_col = nombres{j};

            if isnumeric(valor)

                if contains(nombre_col, 'rep', 'IgnoreCase', true)
                    datos_txt{i,j} = sprintf('%.0f', valor);

                elseif contains(nombre_col, 'kHz', 'IgnoreCase', true)
                    datos_txt{i,j} = sprintf('%.4f', valor);

                elseif contains(nombre_col, 'dB', 'IgnoreCase', true)
                    datos_txt{i,j} = sprintf('%.4f', valor);

                elseif strcmpi(nombre_col, 'NW')
                    datos_txt{i,j} = sprintf('%.2f', valor);

                else
                    datos_txt{i,j} = sprintf('%.4f', valor);
                end

            elseif islogical(valor)

                if valor
                    datos_txt{i,j} = 'Si';
                else
                    datos_txt{i,j} = 'No';
                end

            elseif isstring(valor)

                datos_txt{i,j} = char(valor);

            elseif ischar(valor)

                datos_txt{i,j} = valor;

            else

                datos_txt{i,j} = char(string(valor));
            end
        end
    end

    nfilas = size(datos_txt,1);
    ncols = size(datos_txt,2);

    %% Tamaño compacto

    margen_izq = 30;
    margen_der = 30;
    margen_sup = 18;
    margen_inf = 25;

    alto_titulo = 55;
    alto_header = 36;
    alto_fila = 34;

    ancho_col = zeros(1,ncols);

    for c = 1:ncols

        nombre_col = nombres{c};

        switch nombre_col

            case {'fc_ref_kHz','fc_local_kHz'}
                ancho_col(c) = 115;

            case {'score_local','ON_dB','OFF_dB'}
                ancho_col(c) = 115;

            case {'rep_0dB','rep_3dB','rep_totales'}
                ancho_col(c) = 105;

            case {'umbral_3dB','NW'}
                ancho_col(c) = 105;

            case {'repeticion'}
                ancho_col(c) = 95;

            case {'score_positivo_0dB','score_positivo_3dB'}
                ancho_col(c) = 155;

            otherwise
                ancho_col(c) = 120;
        end
    end

    ancho_tabla = sum(ancho_col);
    alto_tabla = alto_header + nfilas*alto_fila;

    ancho_fig = margen_izq + ancho_tabla + margen_der;
    alto_fig = margen_sup + alto_titulo + alto_tabla + margen_inf;

    fig = figure('Color','w', ...
        'Units','pixels', ...
        'Position',[80 80 ancho_fig alto_fig], ...
        'Name',titulo_figura, ...
        'NumberTitle','off');

    ax = axes('Parent',fig, ...
        'Units','pixels', ...
        'Position',[0 0 ancho_fig alto_fig]);

    axis(ax, [0 ancho_fig 0 alto_fig]);
    axis(ax, 'off');
    hold(ax, 'on');

    %% Titulo

    text(ax, ancho_fig/2, alto_fig - margen_sup - alto_titulo/2, titulo_figura, ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'FontSize',22, ...
        'Interpreter','none');

    %% Tabla

    x0 = margen_izq;
    y0 = margen_inf + alto_tabla;

    color_header = [0.86 0.86 0.86];
    color_fila_1 = [1 1 1];
    color_fila_2 = [0.92 0.92 0.92];
    color_borde = [0.65 0.65 0.65];

    x = x0;

    for c = 1:ncols

        rectangle(ax, ...
            'Position',[x, y0 - alto_header, ancho_col(c), alto_header], ...
            'FaceColor',color_header, ...
            'EdgeColor',color_borde, ...
            'LineWidth',0.9);

        text(ax, x + ancho_col(c)/2, y0 - alto_header/2, nombres{c}, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle', ...
            'FontWeight','bold', ...
            'FontSize',10, ...
            'Interpreter','none');

        x = x + ancho_col(c);
    end

    for r = 1:nfilas

        y = y0 - alto_header - r*alto_fila;

        if mod(r,2) == 0
            color_fila = color_fila_2;
        else
            color_fila = color_fila_1;
        end

        x = x0;

        for c = 1:ncols

            rectangle(ax, ...
                'Position',[x, y, ancho_col(c), alto_fila], ...
                'FaceColor',color_fila, ...
                'EdgeColor',[0.82 0.82 0.82], ...
                'LineWidth',0.7);

            text(ax, x + ancho_col(c)/2, y + alto_fila/2, datos_txt{r,c}, ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle', ...
                'FontSize',10, ...
                'Interpreter','none');

            x = x + ancho_col(c);
        end
    end

    drawnow;

    print(fig, archivo_png, '-dpng', '-r300');
    savefig(fig, archivo_fig);
end