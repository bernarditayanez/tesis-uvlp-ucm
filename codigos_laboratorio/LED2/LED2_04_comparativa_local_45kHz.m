%% LED2_04_comparativa_local_45kHz.m
%
% INSTRUCCIONES DE USO
% Antes de ejecutar este script, revisar la variable carpeta_base
% y modificarla si los resultados del LED 2 se encuentran en otra ruta local.
% La carpeta indicada debe contener las subcarpetas 01_Periodogram,
% 02_Welch y 03_Multitaper, con los archivos .mat generados previamente
% por los scripts de cada metodo.
%
% Ejemplo:
% carpeta_base = 'C:\Users\NombreUsuario\Desktop\Pruebas LED 2\Resultados_LED2_modificados';

clear; 
clc; 
close all;

%% 1. Carpetas

carpeta_base = 'C:\Users\mudrood\Desktop\Modulo Prof\Archivos Tesis\Toma de Datos\Pruebas LED 2\Resultados_LED2_modificados';

carpeta_periodograma = fullfile(carpeta_base, '01_Periodogram');
carpeta_welch        = fullfile(carpeta_base, '02_Welch');
carpeta_mt           = fullfile(carpeta_base, '03_Multitaper');

carpeta_salida = fullfile(carpeta_base, '04_Comparativa');

if ~exist(carpeta_salida, 'dir')
    mkdir(carpeta_salida);
end

%% 2. Parametros generales

fc_ref_Hz  = 45375;
fc_ref_kHz = fc_ref_Hz / 1e3;

ancho_local_Hz = 2500;

fmin_local = fc_ref_Hz - ancho_local_Hz;
fmax_local = fc_ref_Hz + ancho_local_Hz;

criterio_dB = 3;

c_per = [0.0000 0.4470 0.7410]; 
c_wel = [0.8500 0.3250 0.0980];  
c_mt  = [0.9290 0.6940 0.1250];  

c_ref  = [0.20 0.20 0.20];
c_prom = [0.35 0.35 0.35];
c_crit = [0.45 0.45 0.45];

fprintf('\n============================================\n');
fprintf('COMPARATIVA LOCAL LED 2\n');
fprintf('============================================\n');
fprintf('Carpeta base:\n%s\n', carpeta_base);
fprintf('\nFrecuencia referencia = %.3f Hz = %.3f kHz\n', fc_ref_Hz, fc_ref_kHz);
fprintf('Rango comparativo = %.3f a %.3f kHz\n', fmin_local/1e3, fmax_local/1e3);

%% 3. Buscar archivos .mat

archivo_periodograma = buscar_archivo_mat(carpeta_periodograma, { ...
    'datos_periodogram_LED2_graficas_v2.mat', ...
    'datos_periodograma_LED2_graficas_v2.mat', ...
    'datos_periodogram_LED2*.mat', ...
    'datos_periodograma_LED2*.mat', ...
    '*periodogram*LED2*.mat', ...
    '*periodograma*LED2*.mat'});

archivo_welch = buscar_archivo_mat(carpeta_welch, { ...
    'datos_welch_LED2_graficas_v2.mat', ...
    'datos_welch_LED2*.mat', ...
    '*welch*LED2*.mat'});

archivo_mt = buscar_archivo_mat(carpeta_mt, { ...
    'datos_MT_LED2_V2_local_45kHz.mat', ...
    'datos_MT_LED2_V2_local*.mat', ...
    '*MT*LED2*local*.mat', ...
    '*multitaper*LED2*local*.mat'});

fprintf('\nArchivo Periodograma:\n%s\n', archivo_periodograma);
fprintf('\nArchivo Welch:\n%s\n', archivo_welch);
fprintf('\nArchivo Multitaper:\n%s\n', archivo_mt);

%% 4. Cargar datos

Sper = load(archivo_periodograma);
Swel = load(archivo_welch);
Smt  = load(archivo_mt);

%% 5. Extraer curvas de score

[f_per, score_per] = extraer_curva_score(Sper, 'Periodograma');
[f_wel, score_wel] = extraer_curva_score(Swel, 'Welch');
[f_mt,  score_mt]  = extraer_curva_score(Smt,  'Multitaper local');

f_per = normalizar_frecuencia_Hz(f_per(:));
f_wel = normalizar_frecuencia_Hz(f_wel(:));
f_mt  = normalizar_frecuencia_Hz(f_mt(:));

score_per = score_per(:);
score_wel = score_wel(:);
score_mt  = score_mt(:);

%% 6. Extraer resumen de cada metodo

res_per = extraer_resumen_metodo(Sper, 'Periodograma');
res_wel = extraer_resumen_metodo(Swel, 'Welch');
res_mt  = extraer_resumen_metodo(Smt,  'Multitaper local');

%% 7. Tabla resumen comparativa

tabla_resumen = table( ...
    ["Periodograma"; "Welch"; "Multitaper local"], ...
    [res_per.fc_kHz; res_wel.fc_kHz; res_mt.fc_kHz], ...
    [res_per.score_dB; res_wel.score_dB; res_mt.score_dB], ...
    [res_per.ON_dB; res_wel.ON_dB; res_mt.ON_dB], ...
    [res_per.OFF_dB; res_wel.OFF_dB; res_mt.OFF_dB], ...
    [res_per.rep_0dB; res_wel.rep_0dB; res_mt.rep_0dB], ...
    [res_per.rep_3dB; res_wel.rep_3dB; res_mt.rep_3dB], ...
    [res_per.rep_total; res_wel.rep_total; res_mt.rep_total], ...
    strings(3,1), ...
    abs([res_per.fc_kHz; res_wel.fc_kHz; res_mt.fc_kHz] - fc_ref_kHz), ...
    abs([res_per.fc_kHz; res_wel.fc_kHz; res_mt.fc_kHz] - fc_ref_kHz)/fc_ref_kHz*100, ...
    'VariableNames', { ...
    'Metodo', ...
    'fc_kHz', ...
    'score_max', ...
    'ON_dB', ...
    'OFF_dB', ...
    'rep_0dB', ...
    'rep_3dB', ...
    'rep_total', ...
    'supera_3dB', ...
    'err_ref_kHz', ...
    'err_ref_pct'});

for i = 1:height(tabla_resumen)
    if tabla_resumen.score_max(i) >= criterio_dB
        tabla_resumen.supera_3dB(i) = "Si";
    else
        tabla_resumen.supera_3dB(i) = "No";
    end
end

idx_validados = tabla_resumen.score_max >= criterio_dB;

fc_promedio_kHz = mean(tabla_resumen.fc_kHz, 'omitnan');

if any(idx_validados)
    fc_promedio_validado_kHz = mean(tabla_resumen.fc_kHz(idx_validados), 'omitnan');
else
    fc_promedio_validado_kHz = NaN;
end

if ~isnan(fc_promedio_validado_kHz)
    fc_texto_prom_kHz = fc_promedio_validado_kHz;
else
    fc_texto_prom_kHz = fc_promedio_kHz;
end

tabla_parametros = table( ...
    fc_ref_kHz, ...
    ancho_local_Hz/1e3, ...
    fmin_local/1e3, ...
    fmax_local/1e3, ...
    fc_promedio_kHz, ...
    fc_promedio_validado_kHz, ...
    criterio_dB, ...
    sum(idx_validados), ...
    height(tabla_resumen), ...
    'VariableNames', { ...
    'fc_ref_kHz', ...
    'ancho_kHz', ...
    'fmin_local_kHz', ...
    'fmax_local_kHz', ...
    'fc_prom_gen_kHz', ...
    'fc_prom_val_kHz', ...
    'criterio_dB', ...
    'met_val', ...
    'met_total'});

fprintf('\n============================================\n');
fprintf('TABLA RESUMEN COMPARATIVA LED 2\n');
fprintf('============================================\n');
disp(tabla_resumen);

fprintf('\n============================================\n');
fprintf('PARAMETROS COMPARATIVA LED 2\n');
fprintf('============================================\n');
disp(tabla_parametros);

%% 7.b Tablas auxiliares para figuras

tabla_resumen_fig = tabla_resumen;
tabla_resumen_fig.Properties.VariableNames = { ...
    'Metodo', ...
    'fc_kHz', ...
    'score_max', ...
    'ON_dB', ...
    'OFF_dB', ...
    'rep_0dB', ...
    'rep_3dB', ...
    'rep_total', ...
