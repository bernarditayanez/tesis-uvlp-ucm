    error('Curva local Periodograma vacia. Revisar unidades de frecuencia.');
end

if isempty(f_wel_l)
    error('Curva local Welch vacia. Revisar unidades de frecuencia.');
end

if isempty(f_mt_l)
    error('Curva local Multitaper vacia. Revisar unidades de frecuencia.');
end

