function archivo = buscar_archivo_mat(carpeta, patrones)

    if ~exist(carpeta, 'dir')
        error('No existe la carpeta: %s', carpeta);
    end

    archivo = '';

    for i = 1:numel(patrones)
        D = dir(fullfile(carpeta, patrones{i}));

        if ~isempty(D)
            archivo = fullfile(D(1).folder, D(1).name);
            return;
        end
    end

    D = dir(fullfile(carpeta, '*.mat'));

    if isempty(D)
        error('No se encontro ningun archivo .mat en la carpeta: %s', carpeta);
    end

    fprintf('\nArchivos .mat encontrados en %s:\n', carpeta);
    for k = 1:numel(D)
        fprintf('  %d) %s\n', k, D(k).name);
    end

    error('No se encontro ningun archivo esperado en la carpeta: %s', carpeta);
end

function [f, score] = extraer_curva_score(S, nombre_metodo)

    if isfield(S, 'f')
        f = S.f;
    elseif isfield(S, 'f_Hz')
        f = S.f_Hz;
    elseif isfield(S, 'freq')
        f = S.freq;
    else
        error('No se encontro variable de frecuencia en %s.', nombre_metodo);
    end

    if isfield(S, 'score_prom_dB')
        score = S.score_prom_dB;
    elseif isfield(S, 'score_prom')
        score = S.score_prom;
    elseif isfield(S, 'score_local')
        score = S.score_local;
    elseif isfield(S, 'score_local_dB')
        score = S.score_local_dB;
    elseif isfield(S, 'P_ON_prom_dB') && isfield(S, 'P_OFF_prom_dB')
        score = S.P_ON_prom_dB - S.P_OFF_prom_dB;
    elseif isfield(S, 'P_ON_prom') && isfield(S, 'P_OFF_prom')
        score = S.P_ON_prom - S.P_OFF_prom;
    elseif isfield(S, 'Pxx_ON_prom_dB') && isfield(S, 'Pxx_OFF_prom_dB')
        score = S.Pxx_ON_prom_dB - S.Pxx_OFF_prom_dB;
    else
        error('No se encontro curva de score valida en %s.', nombre_metodo);
    end

    f = f(:);
    score = score(:);

    if numel(f) ~= numel(score)
        error('f y score tienen distinto largo en %s.', nombre_metodo);
    end
end

function f_Hz = normalizar_frecuencia_Hz(f)

    f = f(:);

    if max(f, [], 'omitnan') < 1000
        f_Hz = f * 1e3;
    else
        f_Hz = f;
    end
end

function res = extraer_resumen_metodo(S, nombre_metodo)

    res = struct();
    res.fc_Hz = NaN;
    res.fc_kHz = NaN;
    res.score_dB = NaN;
    res.ON_dB = NaN;
    res.OFF_dB = NaN;
    res.rep_0dB = NaN;
    res.rep_3dB = NaN;
    res.rep_total = NaN;

    if isfield(S, 'tabla_candidatos') && istable(S.tabla_candidatos) && height(S.tabla_candidatos) >= 1
        T = S.tabla_candidatos;
    elseif isfield(S, 'tabla') && istable(S.tabla) && height(S.tabla) >= 1
        T = S.tabla;
    elseif isfield(S, 'tabla_resumen') && istable(S.tabla_resumen) && height(S.tabla_resumen) >= 1
        T = S.tabla_resumen;
    else
        error('No se encontro tabla valida en %s.', nombre_metodo);
    end

    vars = T.Properties.VariableNames;

    if ismember('fc_Hz', vars)
        res.fc_Hz = tomar_valor(T.fc_Hz, 1);
    elseif ismember('f_local_Hz', vars)
        res.fc_Hz = tomar_valor(T.f_local_Hz, 1);
    elseif ismember('fc_local_Hz', vars)
        res.fc_Hz = tomar_valor(T.fc_local_Hz, 1);
    end

    if ismember('fc_kHz', vars)
        res.fc_kHz = tomar_valor(T.fc_kHz, 1);
    elseif ismember('f_local_kHz', vars)
        res.fc_kHz = tomar_valor(T.f_local_kHz, 1);
    elseif ismember('fc_local_kHz', vars)
        res.fc_kHz = tomar_valor(T.fc_local_kHz, 1);
    elseif ~isnan(res.fc_Hz)
        res.fc_kHz = res.fc_Hz / 1e3;
    end

    if isnan(res.fc_Hz) && ~isnan(res.fc_kHz)
        res.fc_Hz = res.fc_kHz * 1e3;
    end

    if ismember('score_local_dB', vars)
        res.score_dB = tomar_valor(T.score_local_dB, 1);
    elseif ismember('score_peak_dB', vars)
        res.score_dB = tomar_valor(T.score_peak_dB, 1);
    elseif ismember('score_max_dB', vars)
        res.score_dB = tomar_valor(T.score_max_dB, 1);
    elseif ismember('score_max', vars)
        res.score_dB = tomar_valor(T.score_max, 1);
    end

    if ismember('ON_dB', vars)
        res.ON_dB = tomar_valor(T.ON_dB, 1);
    end

    if ismember('OFF_dB', vars)
        res.OFF_dB = tomar_valor(T.OFF_dB, 1);
    end

    if ismember('rep_positivas_0dB', vars)
        res.rep_0dB = tomar_valor(T.rep_positivas_0dB, 1);
    elseif ismember('rep_0dB', vars)
        res.rep_0dB = tomar_valor(T.rep_0dB, 1);
    elseif ismember('rep_positivas', vars)
        res.rep_0dB = tomar_valor(T.rep_positivas, 1);
    end

    if ismember('rep_positivas_3dB', vars)
        res.rep_3dB = tomar_valor(T.rep_positivas_3dB, 1);
    elseif ismember('rep_3dB', vars)
        res.rep_3dB = tomar_valor(T.rep_3dB, 1);
    elseif ismember('rep_positivas', vars)
        res.rep_3dB = tomar_valor(T.rep_positivas, 1);
    end

    if ismember('rep_totales', vars)
        res.rep_total = tomar_valor(T.rep_totales, 1);
    elseif ismember('rep_total', vars)
        res.rep_total = tomar_valor(T.rep_total, 1);
    end

    fprintf('\nResumen %s:\n', nombre_metodo);
    fprintf('fc = %.3f Hz = %.4f kHz\n', res.fc_Hz, res.fc_kHz);
    fprintf('score = %.4f dB\n', res.score_dB);
end

function valor = tomar_valor(columna, idx)

    if iscell(columna)
        valor = columna{idx};
    else
        valor = columna(idx);
    end

    if isstring(valor)
        valor = str2double(valor);
    elseif ischar(valor)
        valor = str2double(valor);
    elseif islogical(valor)
        valor = double(valor);
    end

    if isempty(valor)
        valor = NaN;
    end
end

function guardar_tabla_como_figura_ajustada(T, titulo_figura, archivo_png, archivo_fig)

    if isempty(T)
        warning('La tabla esta vacia. No se generara figura: %s', titulo_figura);
        return;
    end

    nombres = T.Properties.VariableNames;
    nFilas = height(T);
    nCols = width(T);

    datos_txt = cell(nFilas, nCols);

    for r = 1:nFilas
        for c = 1:nCols

            valor = T{r,c};
            nombre_col = nombres{c};

            if iscell(valor)
                valor = valor{1};
            end

            nombre_col_lower = lower(nombre_col);

            if isnumeric(valor)
                if contains(nombre_col_lower, 'rep') || contains(nombre_col_lower, 'met_')
                    datos_txt{r,c} = sprintf('%d', round(valor));
                elseif contains(nombre_col_lower, 'pct')
                    datos_txt{r,c} = sprintf('%.2f', valor);
                elseif contains(nombre_col_lower, 'khz')
                    datos_txt{r,c} = sprintf('%.4f', valor);
                elseif contains(nombre_col_lower, 'db') || contains(nombre_col_lower, 'score')
                    datos_txt{r,c} = sprintf('%.4f', valor);
                else
                    datos_txt{r,c} = sprintf('%.4f', valor);
                end

            elseif isstring(valor)
                datos_txt{r,c} = char(valor);

            elseif ischar(valor)
                datos_txt{r,c} = valor;

            elseif islogical(valor)
                if valor
                    datos_txt{r,c} = 'Si';
                else
                    datos_txt{r,c} = 'No';
                end

            else
                datos_txt{r,c} = char(string(valor));
            end
        end
    end

    %% Tamano de figura

    alto_titulo = 75;
    alto_header = 52;
    alto_fila   = 52;
    margen_inf  = 30;
    margen_sup  = 22;

    alto_fig = alto_titulo + alto_header + nFilas*alto_fila + margen_inf + margen_sup;

    ancho_col = zeros(1,nCols);

    for c = 1:nCols
        nombre_col = nombres{c};

        switch nombre_col
            case 'Metodo'
                ancho_col(c) = 180;

            case {'score_max','ON_dB','OFF_dB'}
                ancho_col(c) = 135;

            case {'rep_0dB','rep_3dB','rep_total','met_val','met_total'}
                ancho_col(c) = 115;

            case {'sup_3dB'}
                ancho_col(c) = 120;

            case {'err_kHz','err_pct'}
                ancho_col(c) = 125;

            case {'fc_kHz','fc_ref_kHz','ancho_kHz','fmin_kHz','fmax_kHz','fc_prom_kHz','fc_val_kHz','crit_dB'}
                ancho_col(c) = 135;

            otherwise
                ancho_col(c) = 130;
        end
    end

    margen_izq = 35;
    margen_der = 35;

    ancho_fig = margen_izq + sum(ancho_col) + margen_der;

    fig = figure('Color','w', ...
        'Units','pixels', ...
        'Position',[80 100 ancho_fig alto_fig], ...
        'Name', titulo_figura, ...
        'NumberTitle','off');

    ax = axes('Parent',fig, ...
        'Units','pixels', ...
        'Position',[0 0 ancho_fig alto_fig]);

    axis(ax, [0 ancho_fig 0 alto_fig]);
    axis(ax, 'off');
    hold(ax, 'on');

    %% Titulo

    text(ax, ancho_fig/2, alto_fig - margen_sup - alto_titulo/2, titulo_figura, ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontWeight','bold', ...
        'FontSize',24, ...
        'Interpreter','none');

    %% Tabla

    x0 = margen_izq;
    y0 = margen_inf + alto_header + nFilas*alto_fila;

    color_header = [0.86 0.86 0.86];
    color_fila_1 = [1 1 1];
    color_fila_2 = [0.92 0.92 0.92];
    color_borde = [0.65 0.65 0.65];

    x = x0;

    for c = 1:nCols

        rectangle(ax, ...
            'Position',[x, y0 - alto_header, ancho_col(c), alto_header], ...
            'FaceColor',color_header, ...
            'EdgeColor',color_borde, ...
            'LineWidth',0.9);

        text(ax, x + ancho_col(c)/2, y0 - alto_header/2, nombres{c}, ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle', ...
            'FontWeight','bold', ...
            'FontSize',11, ...
            'Interpreter','none');

        x = x + ancho_col(c);
    end

    for r = 1:nFilas

        y = y0 - alto_header - r*alto_fila;

        if mod(r,2) == 0
            color_fila = color_fila_2;
        else
            color_fila = color_fila_1;
        end

        x = x0;

        for c = 1:nCols

            rectangle(ax, ...
                'Position',[x, y, ancho_col(c), alto_fila], ...
                'FaceColor',color_fila, ...
                'EdgeColor',[0.82 0.82 0.82], ...
                'LineWidth',0.7);

            text(ax, x + ancho_col(c)/2, y + alto_fila/2, datos_txt{r,c}, ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle', ...
                'FontSize',11.5, ...
                'Interpreter','none');

            x = x + ancho_col(c);
        end
    end

    drawnow;

    set(fig, 'PaperPositionMode', 'auto');

    print(fig, archivo_png, '-dpng', '-r220');
    savefig(fig, archivo_fig);
end

